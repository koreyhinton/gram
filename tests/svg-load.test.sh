#!/bin/bash

# Prints the svg-load tests as one Rust file (test.sh writes it to
# tests/svg_load.rs). Each test parses svg text with svg-load.sh, then checks
# the Doc: element order, attribute order, raw text and click boxes.
#
# The interface these tests fix:
#   svg-load.sh  binds Text (&str), declares Doc and Error. The root <svg>'s
#       attributes go to Doc.root_attrs; every other element becomes a Node,
#       in document order, attributes in file order, values and text raw.
#       Node.bounds follows the old web app's setMouseRects.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}load_Text=svg_text
export ${v}load_Doc=doc
export ${v}load_Error=error

cat << EOF
// Code generated by tests/svg-load.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]

use macroquad::prelude::*;

EOF

# the app's constants and types
./models.sh

cat << EOF

// devbox's sample diagram (ActSvg.js svgEx, 2022-09-03), the first thing the
// old app ever drew
const SVG_EX: &str = r#"<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="750" height="750" viewBox="0,0,750,750">
    <circle cx="375" cy="39" r="10" fill="black" stroke="black" stroke-width="1"/>
    <polyline points="375 52 375 108 365 98 375 108 385 98" stroke="black" fill="transparent" stroke-width="1"/>
    <rect rx="10" ry="10" x="325" y="112" width="100" height="50" stroke="black" fill="transparent" stroke-width="1"/>
    <text x="333" y="134" fill="black">Receive</text>
    <text x="333" y="154" fill="black">Request</text>
</svg>"#;

fn pairs(list: &[(&str, &str)]) -> Vec<(String, String)> {
    list.iter().map(|(name, value)| (name.to_string(), value.to_string())).collect()
}

#[test]
fn elements_load_in_document_order_with_attributes_in_file_order() {
    let svg_text = SVG_EX;

    ` ./svg-load.sh ${v}load_ `

    assert_eq!(error, None);
    assert_eq!(
        doc.root_attrs,
        pairs(&[
            ("version", "1.1"),
            ("xmlns", "http://www.w3.org/2000/svg"),
            ("xmlns:xlink", "http://www.w3.org/1999/xlink"),
            ("width", "750"),
            ("height", "750"),
            ("viewBox", "0,0,750,750"),
        ])
    );
    let tags: Vec<&str> = doc.nodes.iter().map(|node| node.tag.as_str()).collect();
    assert_eq!(tags, vec!["circle", "polyline", "rect", "text", "text"]);
    assert_eq!(
        doc.nodes[2].attrs,
        pairs(&[
            ("rx", "10"),
            ("ry", "10"),
            ("x", "325"),
            ("y", "112"),
            ("width", "100"),
            ("height", "50"),
            ("stroke", "black"),
            ("fill", "transparent"),
            ("stroke-width", "1"),
        ])
    );
    assert_eq!(doc.nodes[3].text, "Receive");
    assert_eq!(doc.nodes[4].text, "Request");
}

#[test]
fn text_and_attribute_values_stay_raw() {
    let svg_text = r#"<svg><text x="1" y="2" id="a&amp;b">A &amp; B &lt;C&gt; &#65;</text></svg>"#;

    ` ./svg-load.sh ${v}load_ `

    assert_eq!(error, None);
    assert_eq!(doc.nodes[0].text, "A &amp; B &lt;C&gt; &#65;");
    assert_eq!(doc.nodes[0].attrs[2], ("id".to_string(), "a&amp;b".to_string()));
}

#[test]
fn click_boxes_follow_the_old_rules() {
    let svg_text = SVG_EX;

    ` ./svg-load.sh ${v}load_ `

    assert_eq!(error, None);

    // circle: center +- (r + stroke-width)
    assert_eq!(doc.nodes[0].bounds, Rect::new(364.0, 28.0, 22.0, 22.0));
    // polyline: its points' extent, no stroke
    assert_eq!(doc.nodes[1].bounds, Rect::new(365.0, 52.0, 20.0, 56.0));
    // rect: padded by stroke-width
    assert_eq!(doc.nodes[2].bounds, Rect::new(324.0, 111.0, 102.0, 52.0));
    // text: R(11) e(8) c(8) e(8) i(7) v(8) e(8) = 58 wide, from x - 3, and
    // from y - 17 to y + 4
    assert_eq!(doc.nodes[3].bounds, Rect::new(330.0, 117.0, 61.0, 21.0));
}

#[test]
fn a_line_box_is_padded_by_one_either_way() {
    let svg_text = r#"<svg><line x1="50" y1="20" x2="10" y2="20" stroke="black"/></svg>"#;

    ` ./svg-load.sh ${v}load_ `

    assert_eq!(error, None);

    assert_eq!(doc.nodes[0].bounds, Rect::new(9.0, 19.0, 42.0, 2.0));
}

#[test]
fn text_coordinates_are_truncated_like_parse_int() {
    let svg_text = r#"<svg><text x="10.9" y="20.9">l</text></svg>"#;

    ` ./svg-load.sh ${v}load_ `

    assert_eq!(error, None);

    // l is 7 wide
    assert_eq!(doc.nodes[0].bounds, Rect::new(7.0, 3.0, 10.0, 21.0));
}

#[test]
fn invalid_xml_is_an_error() {
    let svg_text = r#"<svg><rect x="1" y="2"></line></svg>"#;

    ` ./svg-load.sh ${v}load_ `

    assert!(error.is_some(), "expected an error, got {:?}", doc);
}

#[test]
fn a_file_without_an_svg_root_is_an_error() {
    let svg_text = r#"<rect x="1" y="2"/>"#;

    ` ./svg-load.sh ${v}load_ `

    assert_eq!(error, Some("no <svg> root element".to_string()));
}
EOF
