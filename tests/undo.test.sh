#[test]
fn ctrl_z_undoes_and_ctrl_y_or_ctrl_shift_z_redo() {
    let cases = [
        (KeyCode::Z, true, false, Some(CtrlAction::Undo)),
        (KeyCode::Z, true, true, Some(CtrlAction::Redo)),
        (KeyCode::Y, true, false, Some(CtrlAction::Redo)),
        (KeyCode::A, true, false, Some(CtrlAction::SelectAll)),
        // without Ctrl, nothing
        (KeyCode::Z, false, false, None),
        (KeyCode::A, false, false, None),
        // a Ctrl chord gram doesn't use
        (KeyCode::Q, true, false, None),
    ];
    // (declared by ctrl-keys.sh; here too, so a missing snippet fails, not breaks the build)
    let mut action: Option<CtrlAction> = None;
    for (key, ctrl, shift, want) in cases {
        let presses = vec![key];
        ` ./ctrl-keys.sh ${v}ctrl_ `
        assert_eq!(action, want, "{:?} ctrl {} shift {}", key, ctrl, shift);
    }

    // no key pressed this frame
    let presses: Vec<KeyCode> = vec![];
    let (ctrl, shift) = (true, false);
    ` ./ctrl-keys.sh ${v}ctrl_ `
    assert_eq!(action, None);
}

