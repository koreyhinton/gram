    let mut stepped = false;

    ` ./history-push.sh ${v}push_ `
    draw_a_line(&mut doc, 0.0, 0.0, 50.0, 0.0);
    let back = true;
    ` ./history-step.sh ${v}step_ `
    assert_eq!(history.redo.len(), 1);

