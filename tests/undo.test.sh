#[test]
fn the_history_keeps_the_newest_undo_limit_changes() {
    let svg_text = r#"<svg></svg>"#;
    ` ./svg-load.sh ${v}load_ `
    let saved = doc.clone();
    let mut history = History::default();
    let mut dirty = false;
    // (declared by history-step.sh; here too, so a missing snippet fails, not breaks the build)
    let mut stepped = false;
    for i in 0..UNDO_LIMIT + 5 {
        ` ./history-push.sh ${v}push_ `
        draw_a_line(&mut doc, 0.0, i as f32, 50.0, i as f32);
    }
    assert_eq!(history.undo.len(), UNDO_LIMIT);
    // the oldest ones went: the furthest back holds 5 lines, not 0
    assert_eq!(history.undo[0].nodes.len(), 5);

    let back = true;
    let mut steps = 0;
    loop {
        ` ./history-step.sh ${v}step_ `
        if !stepped {
            break;
        }
        steps += 1;
    }
    assert_eq!(steps, UNDO_LIMIT);
    assert_eq!(doc.nodes.len(), 5);
}

