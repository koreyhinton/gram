# Prints the undo, redo and select-all tests as one Rust file (test.sh writes
# it to tests/undo.rs). Step 5a, an unpaired step: CT/56 (v0.3) and act.svg
# issues #27 (CTRL-A) and #31 (CTRL-Z) planned it, and nothing ever built it.
#
# The interface these tests fix:
#   history-push.sh  binds History and Doc. Before a change: pushes a copy of
#       Doc onto History.undo and clears History.redo. At most UNDO_LIMIT
#       snapshots are kept; the oldest goes first.
#   history-step.sh  binds History, Doc, Saved, Back, Dirty and Stepped. One
#       undo (Back true) or redo (Back false): Doc goes onto the other stack
#       and the newest snapshot from this one becomes Doc. Stepped (declared
#       here) says whether there was anything to step to; when there was,
#       Dirty becomes whether Doc differs from Saved, the page as last loaded
#       or saved. With nothing to step to, nothing changes.
#   select-all.sh  binds Doc and Selection. Every shape (SHAPE_TAGS: no <g>,
#       <defs> or <title>), in document order; no group.
#   ctrl-keys.sh  binds Presses, Ctrl, Shift and Action. With Ctrl down: Z
#       undoes, Shift+Z and Y redo, A selects all. Action (declared here) is
#       None otherwise.
#   hud-hints.sh  binds Undo too: with something to undo, the hints end with
#       ", Ctrl-Z: undo".

