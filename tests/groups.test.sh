#!/bin/bash

# Prints the group tests as one Rust file (test.sh writes it to
# tests/groups.rs): selecting the shapes of a <g> with a right-click, going
# up a <g> at a time, and back to single nodes with a left click; and the
# note on pages that use transform.
#
# The interface these tests fix:
#   select-group.sh  binds Doc, Hit and Selection. The shapes inside the
#       nearest <g> around the clicked node (or around the node being
#       edited, on empty space), in document order with the clicked node
#       last. Inside the selected group, or on empty space, it goes one <g>
#       up. No <g> to go to: no change.
#   select.sh  a left click on a node ends a group selection.
#   transform-note.sh  binds Doc and Note. Says how many elements have a
#       transform gram ignores; None when there are none.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}load_Text=svg_text
export ${v}load_Doc=doc
export ${v}load_Error=error
export ${v}group_Doc=doc
export ${v}group_Hit=hit
export ${v}group_Selection=selection
export ${v}sel_Selection=selection
export ${v}sel_Hit=hit
export ${v}note_Doc=doc
export ${v}note_Note=note

cat << EOF
// Code generated by tests/groups.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]
// a test reads only the outputs it checks
#![allow(unused_variables, unused_assignments, unused_mut)]

use macroquad::prelude::*;

EOF

# the app's constants and types
./models.sh

cat << EOF

// node indexes: 0 rect (no group), 1 g outer, 2 rect, 3 g inner, 4 line,
// 5 text, 6 circle, 7 title
const NESTED: &str = r#"<svg><rect x="0" y="0" width="5" height="5"/><g id="outer"><rect x="10" y="10" width="5" height="5"/><g id="inner" stroke="red"><line x1="20" y1="20" x2="30" y2="20"/><text x="30" y="40">a</text></g><circle cx="50" cy="50" r="5"/></g><title>t</title></svg>"#;

fn group_of(selection: &Selection) -> (Vec<usize>, Option<usize>) {
    (selection.ids.clone(), selection.group)
}

#[test]
fn a_right_click_selects_the_shapes_of_the_nearest_group() {
    let svg_text = NESTED;
    ` ./svg-load.sh ${v}load_ `
    assert_eq!(error, None);
    let mut selection = Selection::default();

    // the line: its <g> is "inner"; the line is last, so Enter edits it
    let hit = Some(4);
    ` ./select-group.sh ${v}group_ `
    assert_eq!(group_of(&selection), (vec![5, 4], Some(3)));
}

#[test]
fn each_right_click_goes_one_group_up_then_stops() {
    let svg_text = NESTED;
    ` ./svg-load.sh ${v}load_ `
    let mut selection = Selection::default();

    let hit = Some(4);
    ` ./select-group.sh ${v}group_ `
    // again, on the text inside the selected group: up to "outer"
    let hit = Some(5);
    ` ./select-group.sh ${v}group_ `
    assert_eq!(group_of(&selection), (vec![2, 4, 6, 5], Some(1)));

    // no <g> above "outer" (and the title isn't a shape)
    let hit = Some(6);
    ` ./select-group.sh ${v}group_ `
    assert_eq!(group_of(&selection), (vec![2, 4, 6, 5], Some(1)));
}

#[test]
fn a_node_in_no_group_changes_nothing() {
    let svg_text = NESTED;
    ` ./svg-load.sh ${v}load_ `
    let mut selection = Selection { ids: vec![2], group: None };

    let hit = Some(0);
    ` ./select-group.sh ${v}group_ `
    assert_eq!(group_of(&selection), (vec![2], None));
}

#[test]
fn on_empty_space_it_starts_from_the_node_being_edited() {
    let svg_text = NESTED;
    ` ./svg-load.sh ${v}load_ `

    // nothing selected: nothing to start from
    let mut selection = Selection::default();
    let hit: Option<usize> = None;
    ` ./select-group.sh ${v}group_ `
    assert_eq!(group_of(&selection), (vec![], None));

    // the circle picked by a left click: its group
    let mut selection = Selection { ids: vec![6], group: None };
    ` ./select-group.sh ${v}group_ `
    assert_eq!(group_of(&selection), (vec![2, 4, 5, 6], Some(1)));

    // "inner" selected: empty space goes up, as a click inside it does
    let mut selection = Selection { ids: vec![5, 4], group: Some(3) };
    ` ./select-group.sh ${v}group_ `
    assert_eq!(group_of(&selection), (vec![2, 5, 6, 4], Some(1)));
}

#[test]
fn a_right_click_outside_the_selected_group_starts_over_there() {
    let svg_text = NESTED;
    ` ./svg-load.sh ${v}load_ `
    let mut selection = Selection { ids: vec![5, 4], group: Some(3) };

    // the outer rect isn't in "inner": its own nearest <g> is "outer"
    let hit = Some(2);
    ` ./select-group.sh ${v}group_ `
    assert_eq!(group_of(&selection), (vec![4, 5, 6, 2], Some(1)));
}

#[test]
fn a_left_click_goes_back_to_single_nodes() {
    let mut selection = Selection { ids: vec![5, 4], group: Some(3) };

    let hit = Some(4);
    ` ./select.sh ${v}sel_ `
    assert_eq!(group_of(&selection), (vec![5], None));
}

#[test]
fn a_page_with_transforms_says_so() {
    let svg_text = r#"<svg><g transform="translate(10,0)"><rect transform="scale(2)"/></g><circle/></svg>"#;
    ` ./svg-load.sh ${v}load_ `
    ` ./transform-note.sh ${v}note_ `
    assert_eq!(note, Some("transform isn't supported yet: 2 elements drawn as if it weren't there".to_string()));

    let svg_text = NESTED;
    ` ./svg-load.sh ${v}load_ `
    ` ./transform-note.sh ${v}note_ `
    assert_eq!(note, None);
}
EOF
