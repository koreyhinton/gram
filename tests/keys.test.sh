#!/bin/bash

# Prints the key press tests as one Rust file (test.sh writes it to
# tests/keys.rs). They feed key-presses.sh raw key events, as macroquad
# replays them to an input subscriber.
#
# The interface these tests fix:
#   key-presses.sh  binds Events, Lost and Presses. A down event that isn't
#       a repeat is a press. A key in Lost (its release may have gone to the
#       editor) counts as pressed on its next down event even when miniquad
#       calls it a repeat, then leaves Lost; its up event also takes it out.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}keys_Events=events
export ${v}keys_Lost=lost
export ${v}keys_Presses=presses

cat << EOF
// Code generated by tests/keys.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]

use macroquad::prelude::*;

EOF

# the app's constants and types
./models.sh

cat << EOF

fn down(key: KeyCode, repeat: bool) -> KeyEvent {
    KeyEvent::Down { key, repeat }
}

#[test]
fn a_press_counts_once_and_holding_it_doesnt_repeat_it() {
    let mut lost: Vec<KeyCode> = vec![];

    let events = vec![down(KeyCode::Enter, false)];
    ` ./key-presses.sh ${v}keys_ `
    assert_eq!(presses, vec![KeyCode::Enter]);

    // held: auto-repeat isn't a press
    let events = vec![down(KeyCode::Enter, true), down(KeyCode::Enter, true)];
    ` ./key-presses.sh ${v}keys_ `
    assert_eq!(presses, vec![]);

    let events = vec![KeyEvent::Up { key: KeyCode::Enter }, down(KeyCode::Enter, false)];
    ` ./key-presses.sh ${v}keys_ `
    assert_eq!(presses, vec![KeyCode::Enter]);
}

#[test]
fn enter_works_again_after_the_editor_took_its_release() {
    // Enter opened the editor while held; its up event went to the editor
    let mut lost = vec![KeyCode::Enter];

    // back in gram, the next Enter: miniquad calls it a repeat
    let events = vec![down(KeyCode::Enter, true)];
    ` ./key-presses.sh ${v}keys_ `
    assert_eq!(presses, vec![KeyCode::Enter]);
    assert_eq!(lost, vec![]);

    // held now: its repeats aren't presses again
    let events = vec![down(KeyCode::Enter, true)];
    ` ./key-presses.sh ${v}keys_ `
    assert_eq!(presses, vec![]);
}

#[test]
fn a_release_that_did_arrive_ends_the_watch() {
    // a quick tap: the up event reached gram before the editor took focus
    let mut lost = vec![KeyCode::Enter, KeyCode::R];

    let events = vec![KeyEvent::Up { key: KeyCode::Enter }];
    ` ./key-presses.sh ${v}keys_ `
    assert_eq!(presses, vec![]);
    assert_eq!(lost, vec![KeyCode::R]);

    // so a later repeat of Enter is an ordinary repeat
    let events = vec![down(KeyCode::Enter, false), down(KeyCode::Enter, true)];
    ` ./key-presses.sh ${v}keys_ `
    assert_eq!(presses, vec![KeyCode::Enter]);
}
EOF
