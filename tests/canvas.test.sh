#!/bin/bash

# Prints the canvas tests as one Rust file (test.sh writes it to
# tests/canvas.rs). They play frames through canvas-update.sh and
# canvas-fit.sh with the mouse, keys and screen stubbed: local fns shadow
# macroquad's glob import and read a scripted state.
#
# The interface these tests fix:
#   canvas-update.sh  binds Canvas. Middle-drag, or Space + left-drag, moves
#       the world with the mouse; the wheel zooms by ZOOM_STEP a notch,
#       clamped to ZOOM_MIN..ZOOM_MAX, keeping the point under the cursor.
#   canvas-fit.sh     binds Canvas and Left. Zooms so the page fits the
#       screen right of Left (the tree panel) less FIT_MARGIN, and centers
#       the page there.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}pan_Canvas=canvas
export ${v}fit_Canvas=canvas
export ${v}fit_Left=0.0
export ${v}fitp_Canvas=canvas
export ${v}fitp_Left=TREE_W

cat << EOF
// Code generated by tests/canvas.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]

use macroquad::prelude::*;
use std::cell::RefCell;

EOF

# the app's constants and types
./models.sh

cat << EOF

// the input as the stubs report it for the current frame
#[derive(Clone, Copy, Default)]
struct Input {
    mouse: (f32, f32),
    middle: bool,
    left: bool,
    space: bool,
    wheel: f32,
    screen: (f32, f32),
}

thread_local! {
    static INPUT: RefCell<Input> = RefCell::new(Input::default());
}

fn set_input(input: Input) {
    INPUT.with(|state| *state.borrow_mut() = input);
}

fn input() -> Input {
    INPUT.with(|state| *state.borrow())
}

fn mouse_position() -> (f32, f32) {
    input().mouse
}

fn is_mouse_button_down(button: MouseButton) -> bool {
    match button {
        MouseButton::Middle => input().middle,
        MouseButton::Left => input().left,
        _ => false,
    }
}

fn is_key_down(key: KeyCode) -> bool {
    key == KeyCode::Space && input().space
}

fn mouse_wheel() -> (f32, f32) {
    (0.0, input().wheel)
}

fn screen_width() -> f32 {
    input().screen.0
}

fn screen_height() -> f32 {
    input().screen.1
}

fn new_canvas(offset: Vec2, zoom: f32) -> Canvas {
    Canvas { offset, zoom, panning: false, last_mouse: Vec2::ZERO }
}

// the world point at a screen point
fn world_at(canvas: &Canvas, screen: (f32, f32)) -> Vec2 {
    canvas.offset + Vec2::from(screen) / canvas.zoom
}

#[test]
fn the_wheel_zooms_in_about_the_cursor() {
    let mut canvas = new_canvas(vec2(-100.0, 50.0), 1.0);
    let cursor = (300.0, 200.0);
    let before = world_at(&canvas, cursor);
    set_input(Input { mouse: cursor, wheel: 1.0, ..Default::default() });

    ` ./canvas-update.sh ${v}pan_ `

    assert!((canvas.zoom - ZOOM_STEP).abs() < 1e-5);
    assert!(world_at(&canvas, cursor).distance(before) < 1e-3);
}

#[test]
fn the_wheel_zooms_out_about_the_cursor() {
    let mut canvas = new_canvas(vec2(20.0, 30.0), 2.0);
    let cursor = (640.0, 10.0);
    let before = world_at(&canvas, cursor);
    set_input(Input { mouse: cursor, wheel: -1.0, ..Default::default() });

    ` ./canvas-update.sh ${v}pan_ `

    assert!((canvas.zoom - 2.0 / ZOOM_STEP).abs() < 1e-5);
    assert!(world_at(&canvas, cursor).distance(before) < 1e-3);
}

#[test]
fn zoom_stops_at_its_limits() {
    let mut canvas = new_canvas(Vec2::ZERO, ZOOM_MAX);
    set_input(Input { mouse: (10.0, 10.0), wheel: 1.0, ..Default::default() });

    ` ./canvas-update.sh ${v}pan_ `

    assert_eq!(canvas.zoom, ZOOM_MAX);

    canvas.zoom = ZOOM_MIN;
    set_input(Input { mouse: (10.0, 10.0), wheel: -1.0, ..Default::default() });

    ` ./canvas-update.sh ${v}pan_ `

    assert_eq!(canvas.zoom, ZOOM_MIN);
}

#[test]
fn a_middle_drag_moves_the_world_with_the_mouse() {
    let mut canvas = new_canvas(vec2(0.0, 0.0), 2.0);

    // press, then move 40 right and 20 down
    set_input(Input { mouse: (100.0, 100.0), middle: true, ..Default::default() });
    ` ./canvas-update.sh ${v}pan_ `
    let grabbed = world_at(&canvas, (100.0, 100.0));
    set_input(Input { mouse: (140.0, 120.0), middle: true, ..Default::default() });
    ` ./canvas-update.sh ${v}pan_ `

    // the world point that was under the mouse still is
    assert!(world_at(&canvas, (140.0, 120.0)).distance(grabbed) < 1e-4);
    assert_eq!(canvas.offset, vec2(-20.0, -10.0));
}

#[test]
fn space_and_a_left_drag_pans_but_a_left_drag_alone_does_not() {
    let mut canvas = new_canvas(Vec2::ZERO, 1.0);

    set_input(Input { mouse: (0.0, 0.0), left: true, ..Default::default() });
    ` ./canvas-update.sh ${v}pan_ `
    set_input(Input { mouse: (50.0, 50.0), left: true, ..Default::default() });
    ` ./canvas-update.sh ${v}pan_ `
    assert_eq!(canvas.offset, Vec2::ZERO);

    set_input(Input { mouse: (50.0, 50.0), left: true, space: true, ..Default::default() });
    ` ./canvas-update.sh ${v}pan_ `
    set_input(Input { mouse: (80.0, 60.0), left: true, space: true, ..Default::default() });
    ` ./canvas-update.sh ${v}pan_ `
    assert_eq!(canvas.offset, vec2(-30.0, -10.0));
}

#[test]
fn a_new_drag_does_not_jump_to_where_the_mouse_was() {
    let mut canvas = new_canvas(Vec2::ZERO, 1.0);

    // the mouse moves with no button down, then a drag starts far away
    set_input(Input { mouse: (10.0, 10.0), ..Default::default() });
    ` ./canvas-update.sh ${v}pan_ `
    set_input(Input { mouse: (500.0, 500.0), middle: true, ..Default::default() });
    ` ./canvas-update.sh ${v}pan_ `

    assert_eq!(canvas.offset, Vec2::ZERO);
}

#[test]
fn fit_centers_the_page_inside_the_margin() {
    let mut canvas = new_canvas(vec2(999.0, -999.0), 7.0);
    set_input(Input { screen: (1280.0, 900.0), ..Default::default() });

    ` ./canvas-fit.sh ${v}fit_ `

    // the height is the tighter fit: (900 - 2 * margin) / 750
    assert!((canvas.zoom - (900.0 - 2.0 * FIT_MARGIN) / PAGE_H).abs() < 1e-5);
    // the page's center is the screen's center
    let center = world_at(&canvas, (640.0, 450.0));
    assert!(center.distance(vec2(PAGE_W / 2.0, PAGE_H / 2.0)) < 1e-3);
}

#[test]
fn fit_centers_the_page_right_of_the_tree_panel() {
    let mut canvas = new_canvas(Vec2::ZERO, 1.0);
    set_input(Input { screen: (1280.0, 900.0), ..Default::default() });

    ` ./canvas-fit.sh ${v}fitp_ `

    // the page's center is the center of the screen right of the panel
    let center = world_at(&canvas, (TREE_W + (1280.0 - TREE_W) / 2.0, 450.0));
    assert!(center.distance(vec2(PAGE_W / 2.0, PAGE_H / 2.0)) < 1e-3);
    // and the page's left edge is right of the panel
    let left_edge = (0.0 - canvas.offset.x) * canvas.zoom;
    assert!(left_edge >= TREE_W + FIT_MARGIN - 1e-3, "page starts at {}", left_edge);
}
EOF
