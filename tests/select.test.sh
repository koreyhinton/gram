#[test]
fn a_node_edit_round_trip_moves_the_selection_together() {
    // the old TDD TEST 0's clicks, less the text it didn't have yet
    let svg_text = SVG_EX;
    ` ./svg-load.sh ${v}load_ `
    ` ./mouse-rects.sh ${v}rects_ `
    ` ./spatial-index.sh ${v}index_ `
    let mut selection = Selection::default();
    for click in [(378.0, 41.0), (376.0, 92.0), (412.0, 113.0)] {
        let pos = vec2(click.0, click.1);
        ` ./hit-test.sh ${v}hit_ `
        ` ./select.sh ${v}sel_ `
    }
    assert_eq!(selection.ids, vec![0, 1, 2]);

    // the edited node (the rect, last selected) out to the editor
    let id = *selection.ids.last().unwrap();
    ` ./node-xml.sh ${v}xml_ `
    let dir = std::env::temp_dir().join(format!("gram-test-{}-node-edit", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("node.xml");
    std::fs::write(&path, &xml).unwrap();
    let editor = "sed -i s/325/25/";
    ` ./editor-open.sh ${v}open_ `
    let mut polls = 0;
    let mut seen_exit = false;
    while !seen_exit && polls < 500 {
        ` ./editor-poll.sh ${v}poll_ `
        seen_exit = exited;
        if !seen_exit {
            std::thread::sleep(std::time::Duration::from_millis(10));
        }
        polls += 1;
    }
    assert!(seen_exit);

    // back in: one element, applied, then carried over
    let edit_text = format!("<svg>{}</svg>", std::fs::read_to_string(&path).unwrap());
    ` ./svg-load.sh ${v}eload_ `
    assert_eq!(edit_error, None);
    assert_eq!(edited.nodes.len(), 1);
    let before = doc.nodes[id].clone();
    ` ./node-apply.sh ${v}apply_ `
    let after = doc.nodes[id].clone();
    let others: Vec<usize> = selection.ids[..selection.ids.len() - 1].to_vec();
    ` ./map.sh ${v}map_ `
    ` ./mouse-rects.sh ${v}rects_ `

    assert_eq!(attr(&doc.nodes[2], "x"), "25");
    assert_eq!(attr(&doc.nodes[0], "cx"), "75");
    assert_eq!(attr(&doc.nodes[1], "points"), "75 52 75 110 65 100 75 110 85 100");
    // the rect's click box moved with it
    assert_eq!(doc.nodes[2].bounds.x, 24.0);
}

