#[test]
fn an_edit_updates_and_adds_attributes_but_never_removes_one() {
    let svg_text = r#"<svg><rect x="1" y="2" data-keep="yes" stroke="black"/></svg>"#;
    ` ./svg-load.sh ${v}load_ `
    let id = 0;
    // the edit drops data-keep, changes x and adds fill
    let edit_text = r#"<svg><circle x="9" stroke="black" fill="red"/></svg>"#;
    ` ./svg-load.sh ${v}eload_ `

    ` ./node-apply.sh ${v}apply_ `

    assert_eq!(doc.nodes[0].tag, "circle");
    assert_eq!(
        doc.nodes[0].attrs,
        vec![
            ("x".to_string(), "9".to_string()),
            ("y".to_string(), "2".to_string()),
            ("data-keep".to_string(), "yes".to_string()),
            ("stroke".to_string(), "black".to_string()),
            ("fill".to_string(), "red".to_string()),
        ]
    );
}

// ---- carrying an edit over ----

#[test]
fn an_edit_moves_the_other_selected_nodes_of_other_kinds() {
    // a rect, a circle and a polyline; each in turn is the edited node,
    // moved by (-300, 20) with its stroke 2 wider
    let shapes = [
        (r#"<rect x="325" y="112" stroke-width="1"/>"#, r#"<rect x="25" y="132" stroke-width="3"/>"#),
        (r#"<circle cx="375" cy="40" stroke-width="1"/>"#, r#"<circle cx="75" cy="60" stroke-width="3"/>"#),
        (
            r#"<polyline points="375 52 375 110" stroke-width="1"/>"#,
            r#"<polyline points="75 72 75 130" stroke-width="3"/>"#,
        ),
    ];
    for (edited_i, (old, new)) in shapes.iter().enumerate() {
        let svg_text = format!("<svg>{}{}{}</svg>", shapes[0].0, shapes[1].0, shapes[2].0);
        ` ./svg-load.sh ${v}load_ `
        let before = doc.nodes[edited_i].clone();
        let edit_text = format!("<svg>{}</svg>", new);
        ` ./svg-load.sh ${v}eload_ `
        let after = edited.nodes[0].clone();
        doc.nodes[edited_i] = after.clone();
        let others: Vec<usize> = (0..3).filter(|i| *i != edited_i).collect();

        ` ./map.sh ${v}map_ `

        let rect = &doc.nodes[0];
        let circle = &doc.nodes[1];
        let polyline = &doc.nodes[2];
        assert_eq!((attr(rect, "x"), attr(rect, "y")), ("25", "132"), "edited {}", edited_i);
        assert_eq!((attr(circle, "cx"), attr(circle, "cy")), ("75", "60"), "edited {}", edited_i);
        assert_eq!(attr(polyline, "points"), "75 72 75 130", "edited {}", edited_i);
        for node in &doc.nodes {
            assert_eq!(attr(node, "stroke-width"), "3", "edited {}: {:?}", edited_i, node);
        }
    }
}

#[test]
fn nodes_of_the_same_kind_dont_follow_yet() {
    // step 3 maps only pairs of different kinds (rect->rect comes at step 4)
    let svg_text = r#"<svg><rect x="10" y="10"/><rect x="50" y="50"/></svg>"#;
    ` ./svg-load.sh ${v}load_ `
    let before = doc.nodes[0].clone();
    let edit_text = r#"<svg><rect x="20" y="10"/></svg>"#;
    ` ./svg-load.sh ${v}eload_ `
    let after = edited.nodes[0].clone();
    doc.nodes[0] = after.clone();
    let others = vec![1usize];

    ` ./map.sh ${v}map_ `

    assert_eq!(attr(&doc.nodes[1], "x"), "50");
}

#[test]
fn numbers_are_written_back_as_js_wrote_them() {
    // parseFloat reads "10px" as 10; the sum is written as a plain number
    let svg_text = r#"<svg><circle cx="5" cy="5"/><rect x="10px" y="0.1"/></svg>"#;
    ` ./svg-load.sh ${v}load_ `
    let before = doc.nodes[0].clone();
    let edit_text = r#"<svg><circle cx="6.5" cy="5.2"/></svg>"#;
    ` ./svg-load.sh ${v}eload_ `
    let after = edited.nodes[0].clone();
    doc.nodes[0] = after.clone();
    let others = vec![1usize];

    ` ./map.sh ${v}map_ `

    assert_eq!(attr(&doc.nodes[1], "x"), "11.5");
    // 0.1 + 0.2 as JS (and Rust's shortest form) writes it
    assert_eq!(attr(&doc.nodes[1], "y"), format!("{}", 0.1f64 + (5.2f64 - 5.0)));
}

// ---- the whole node edit, with sed as the editor ----

#[test]
fn a_node_edit_round_trip_moves_the_selection_together() {
    // the old TDD TEST 0's clicks, less the text it didn't have yet
    let svg_text = SVG_EX;
    ` ./svg-load.sh ${v}load_ `
    ` ./mouse-rects.sh ${v}rects_ `
    ` ./spatial-index.sh ${v}index_ `
    let mut selection = Selection::default();
    for click in [(378.0, 41.0), (376.0, 92.0), (412.0, 113.0)] {
        let pos = vec2(click.0, click.1);
        ` ./hit-test.sh ${v}hit_ `
        ` ./select.sh ${v}sel_ `
    }
    assert_eq!(selection.ids, vec![0, 1, 2]);

    // the edited node (the rect, last selected) out to the editor
    let id = *selection.ids.last().unwrap();
    ` ./node-xml.sh ${v}xml_ `
    let dir = std::env::temp_dir().join(format!("gram-test-{}-node-edit", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("node.svg");
    std::fs::write(&path, &xml).unwrap();
    let editor = "sed -i s/325/25/";
    ` ./editor-open.sh ${v}open_ `
    let mut polls = 0;
    let mut seen_exit = false;
    while !seen_exit && polls < 500 {
        ` ./editor-poll.sh ${v}poll_ `
        seen_exit = exited;
        if !seen_exit {
            std::thread::sleep(std::time::Duration::from_millis(10));
        }
        polls += 1;
    }
    assert!(seen_exit);

    // back in: one element, applied, then carried over
    let edit_text = format!("<svg>{}</svg>", std::fs::read_to_string(&path).unwrap());
    ` ./svg-load.sh ${v}eload_ `
    assert_eq!(edit_error, None);
    assert_eq!(edited.nodes.len(), 1);
    let before = doc.nodes[id].clone();
    ` ./node-apply.sh ${v}apply_ `
    let after = doc.nodes[id].clone();
    let others: Vec<usize> = selection.ids[..selection.ids.len() - 1].to_vec();
    ` ./map.sh ${v}map_ `
    ` ./mouse-rects.sh ${v}rects_ `

    assert_eq!(attr(&doc.nodes[2], "x"), "25");
    assert_eq!(attr(&doc.nodes[0], "cx"), "75");
    assert_eq!(attr(&doc.nodes[1], "points"), "75 52 75 110 65 100 75 110 85 100");
    // the rect's click box moved with it
    assert_eq!(doc.nodes[2].bounds.x, 24.0);
}

#[test]
fn an_edit_that_isnt_one_element_is_refused() {
    let edit_text = r#"<svg><rect x="1"/><rect x="2"/></svg>"#;
    ` ./svg-load.sh ${v}eload_ `
    assert_eq!(edited.nodes.len(), 2);

    let edit_text = r#"<svg><rect x="1"</svg>"#;
    ` ./svg-load.sh ${v}eload_ `
    assert!(edit_error.is_some());
}
