#!/bin/bash

# Prints the selection and node edit tests as one Rust file (test.sh writes
# it to tests/select.rs). They follow the old web app's first ActSvg
# (devbox@c702432): click to select, the selection colors, a node out as
# XML, the edit back in, and the edit carried over to the other selected
# nodes; then its text nodes (devbox@8c8c666). A node edit round trip runs a
# real editor process (sed -i). Last, the old app's first TDD tests
# (devbox@ed1a227): TDD TEST 0 and 1, whose fixes gram already has.
#
# The interface these tests fix:
#   hit-test.sh    binds Doc, Index, Pos and Hit. Of the shapes whose click
#       box holds the point, edges included: text first, then the first in
#       document order.
#   select.sh      binds Selection and Hit. A click toggles the node; the
#       last selected is the one being edited; empty space changes nothing.
#   node-xml.sh    binds Node and Xml. <tag a="v" .../>, attributes in order;
#       a text node holds its raw text.
#   node-apply.sh  binds Edited and Target. Replaces the tag (and a text's
#       text); updates or adds each attribute; removes none.
#   map.sh         binds Before, After, Others and Nodes. The edited node's
#       change of anchor (rect and text x/y, circle cx/cy, polyline first
#       point) moves each other selected node, for any pair among rect,
#       circle, polyline and text; its stroke-width change is added between
#       shapes that aren't text. From devbox@8faf51d, lines too: a line's
#       anchor is x1, y1, and a line that follows moves whole (both ends); a
#       line following a line takes each end's own change.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}load_Text=svg_text
export ${v}load_Doc=doc
export ${v}load_Error=error
export ${v}rects_Nodes=doc.nodes
export ${v}index_Doc=doc
export ${v}index_Index=index
export ${v}hit_Doc=doc
export ${v}hit_Index=index
export ${v}hit_Pos=pos
export ${v}hit_Hit=hit
export ${v}sel_Selection=selection
export ${v}sel_Hit=hit
export ${v}xml_Node=\(\&doc.nodes[id]\)
export ${v}xml_Xml=xml
export ${v}apply_Edited=\(\&edited.nodes[0]\)
export ${v}apply_Target=doc.nodes[id]
export ${v}map_Before=\(\&before\)
export ${v}map_After=\(\&after\)
export ${v}map_Others=\(\&others\)
export ${v}map_Nodes=doc.nodes
export ${v}line_Nodes=doc.nodes
export ${v}line_Pos=pos
export ${v}line_From=from
export ${v}rect_Pos=pos
export ${v}rect_From=from
export ${v}rect_Nodes=doc.nodes
export ${v}rect_Radius=radius
export ${v}line_Width=width
# the edit's XML, read back
export ${v}eload_Text=edit_text
export ${v}eload_Doc=edited
export ${v}eload_Error=edit_error
# the editor
export ${v}open_Editor=editor
export ${v}open_Path=path.as_path\(\)
export ${v}open_Child=child
export ${v}open_Error=open_error
export ${v}poll_Child=child
export ${v}poll_Exited=exited
export ${v}poll_Failed=failed

cat << EOF
// Code generated by tests/select.test.sh. DO NOT EDIT.
