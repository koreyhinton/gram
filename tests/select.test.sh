#!/bin/bash

# Prints the selection and node edit tests as one Rust file (test.sh writes
# it to tests/select.rs). They follow the old web app's first ActSvg
# (devbox@c702432): click to select, the selection colors, a node out as
# XML, the edit back in, and the edit carried over to the other selected
# nodes. A node edit round trip runs a real editor process (sed -i).
#
# The interface these tests fix:
#   hit-test.sh    binds Doc, Index, Pos and Hit. The first node in document
#       order whose click box holds the point, edges included; shapes only.
#   select.sh      binds Selection and Hit. A click toggles the node; the
#       last selected is the one being edited; empty space changes nothing.
#   node-xml.sh    binds Node and Xml. <tag a="v" .../>, attributes in order.
#   node-apply.sh  binds Edited and Target. Replaces the tag; updates or adds
#       each attribute; removes none.
#   map.sh         binds Before, After, Others and Nodes. The edited node's
#       change of anchor (rect x/y, circle cx/cy, polyline first point) moves
#       each other selected node, and its stroke-width change is added, for
#       pairs of different kinds among rect, circle and polyline.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}load_Text=svg_text
export ${v}load_Doc=doc
export ${v}load_Error=error
export ${v}rects_Nodes=doc.nodes
export ${v}index_Doc=doc
export ${v}index_Index=index
export ${v}hit_Doc=doc
export ${v}hit_Index=index
export ${v}hit_Pos=pos
export ${v}hit_Hit=hit
export ${v}sel_Selection=selection
export ${v}sel_Hit=hit
export ${v}xml_Node=\(\&doc.nodes[id]\)
export ${v}xml_Xml=xml
export ${v}apply_Edited=\(\&edited.nodes[0]\)
export ${v}apply_Target=doc.nodes[id]
export ${v}map_Before=\(\&before\)
export ${v}map_After=\(\&after\)
export ${v}map_Others=\(\&others\)
export ${v}map_Nodes=doc.nodes
# the edit's XML, read back
export ${v}eload_Text=edit_text
export ${v}eload_Doc=edited
export ${v}eload_Error=edit_error
# the editor
export ${v}open_Editor=editor
export ${v}open_Path=path.as_path\(\)
export ${v}open_Child=child
export ${v}open_Error=open_error
export ${v}poll_Child=child
export ${v}poll_Exited=exited
export ${v}poll_Failed=failed

cat << EOF
// Code generated by tests/select.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]
// a test reads only the outputs it checks
#![allow(unused_variables, unused_assignments, unused_mut)]

use macroquad::prelude::*;

EOF

# the app's constants and types
./models.sh

cat << EOF

// the old web app's example drawing (svgEx in devbox@c702432), whose text
// was still commented out
const SVG_EX: &str = r#"<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="750" height="750" viewBox="0,0,750,750">
    <circle cx="375" cy="40" r="10" stroke="black" stroke-width="1"/>
    <polyline points="375 52 375 110 365 100 375 110 385 100" stroke="black" fill="transparent" stroke-width="1"/>
    <rect rx="10" ry="10" x="325" y="112" width="100" height="50" stroke="black" fill="transparent" stroke-width="1"/>
</svg>"#;

fn attr<'a>(node: &'a Node, name: &str) -> &'a str {
    node.attrs.iter().find(|(have, _)| have == name).map(|(_, value)| value.as_str()).unwrap_or("")
}

// ---- hit testing ----

#[test]
fn a_click_finds_the_node_under_it_edges_included() {
    let svg_text = SVG_EX;
    ` ./svg-load.sh ${v}load_ `
    ` ./mouse-rects.sh ${v}rects_ `
    ` ./spatial-index.sh ${v}index_ `

    // the rect's box is 324..426 by 111..163 (padded by its stroke)
    let pos = vec2(324.0, 111.0);
    ` ./hit-test.sh ${v}hit_ `
    assert_eq!(hit, Some(2));

    let pos = vec2(323.5, 140.0);
    ` ./hit-test.sh ${v}hit_ `
    assert_eq!(hit, None);

    // the circle, from the old app's TDD TEST 0 (378, 41)
    let pos = vec2(378.0, 41.0);
    ` ./hit-test.sh ${v}hit_ `
    assert_eq!(hit, Some(0));
}

