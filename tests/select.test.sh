// ---- selecting ----

#[test]
fn a_click_selects_and_a_second_click_deselects() {
    let mut selection = Selection::default();

    let hit = Some(0);
    ` ./select.sh ${v}sel_ `
    let hit = Some(2);
    ` ./select.sh ${v}sel_ `
    // the last one selected is the one being edited
    assert_eq!(selection.ids, vec![0, 2]);

    let hit = Some(0);
    ` ./select.sh ${v}sel_ `
    assert_eq!(selection.ids, vec![2]);

    // empty space changes nothing
    let hit: Option<usize> = None;
    ` ./select.sh ${v}sel_ `
    assert_eq!(selection.ids, vec![2]);
}

