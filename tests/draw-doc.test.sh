#!/bin/bash

# Prints the draw-doc tests as one Rust file (test.sh writes it to
# tests/draw_doc.rs). Each test loads svg text (svg-load.sh), indexes it
# (spatial-index.sh) and draws it once (draw-doc.sh). The drawing functions
# are stubbed: local fns shadow macroquad's glob import, so the snippet calls
# the stubs, which record each call instead of needing a window.
#
# The interface these tests fix:
#   draw-doc.sh  binds Doc, Index, Canvas and Font. It draws only the nodes
#       whose bounds touch the view, in document order: fills as triangles,
#       strokes as draw_line segments (cut into dashes by stroke-dasharray),
#       text with draw_text_ex at its baseline, decoded, at its font-size.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}load_Text=svg_text
export ${v}load_Doc=doc
export ${v}rects_Nodes=doc.nodes
export ${v}load_Error=error
export ${v}index_Doc=doc
export ${v}index_Index=index
export ${v}draw_Doc=doc
export ${v}draw_Index=index
export ${v}draw_Canvas=canvas
export ${v}draw_Font=None
# no selection, unless a test maps its own
export ${v}draw_Selection=Selection::default\(\)
# the same, with a selection
export ${v}dsel_Doc=doc
export ${v}dsel_Index=index
export ${v}dsel_Canvas=canvas
export ${v}dsel_Font=None
export ${v}dsel_Selection=selection

cat << EOF
// Code generated by tests/draw-doc.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]

use macroquad::prelude::*;
use std::cell::RefCell;

EOF

# the app's constants and types
./models.sh

cat << EOF

// what one stubbed draw call would have drawn
#[derive(Debug, Clone, PartialEq)]
enum Drawn {
    Line { from: Vec2, to: Vec2, thickness: f32, color: Color },
    Triangle { corners: [Vec2; 3], color: Color },
    // size is the text's size in world units (font_size * font_scale)
    // px is the size the glyphs were rasterized at
    Text { text: String, x: f32, y: f32, size: f32, px: u16, color: Color },
}

thread_local! {
    static DRAWN: RefCell<Vec<Drawn>> = RefCell::new(Vec::new());
}

fn record(drawn: Drawn) {
    DRAWN.with(|list| list.borrow_mut().push(drawn));
}

fn drawn() -> Vec<Drawn> {
    DRAWN.with(|list| list.borrow_mut().drain(..).collect())
}

fn lines(list: &[Drawn]) -> Vec<(Vec2, Vec2)> {
    list.iter()
        .filter_map(|drawn| match drawn {
            Drawn::Line { from, to, .. } => Some((*from, *to)),
            _ => None,
        })
        .collect()
}

fn triangles(list: &[Drawn]) -> Vec<Color> {
    list.iter()
        .filter_map(|drawn| match drawn {
            Drawn::Triangle { color, .. } => Some(*color),
            _ => None,
        })
        .collect()
}

fn draw_line(x1: f32, y1: f32, x2: f32, y2: f32, thickness: f32, color: Color) {
    record(Drawn::Line { from: vec2(x1, y1), to: vec2(x2, y2), thickness, color });
}

fn draw_triangle(v1: Vec2, v2: Vec2, v3: Vec2, color: Color) {
    record(Drawn::Triangle { corners: [v1, v2, v3], color });
}

// the filled triangles' corners
fn fill_triangles(list: &[Drawn]) -> Vec<[Vec2; 3]> {
    list.iter()
        .filter_map(|drawn| match drawn {
            Drawn::Triangle { corners, .. } => Some(*corners),
            _ => None,
        })
        .collect()
}

fn draw_text_ex(text: &str, x: f32, y: f32, params: TextParams) {
    record(Drawn::Text {
        text: text.to_string(),
        x,
        y,
        size: params.font_size as f32 * params.font_scale,
        px: params.font_size,
        color: params.color,
    });
}

// a stand-in width: 0.6em per character (the real font is proportional)
fn measure_text(text: &str, _font: Option<&Font>, font_size: u16, font_scale: f32) -> TextDimensions {
    TextDimensions {
        width: text.chars().count() as f32 * font_size as f32 * font_scale * 0.6,
        height: font_size as f32 * font_scale,
        offset_y: font_size as f32 * font_scale,
    }
}

// a 1000x1000 screen
fn screen_width() -> f32 {
    1000.0
}

fn screen_height() -> f32 {
    1000.0
}

// the canvas at 100% with the page's top-left at the screen's
fn canvas_at(zoom: f32) -> Canvas {
    Canvas { offset: Vec2::ZERO, zoom, panning: false, last_mouse: Vec2::ZERO }
}

