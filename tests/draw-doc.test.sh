#[test]
fn text_is_rasterized_at_its_screen_size() {
    let svg_text = r#"<svg><text x="10" y="20">zoomed</text></svg>"#;
    let canvas = canvas_at(4.0);

    ` ./svg-load.sh ${v}load_ `
    assert_eq!(error, None);
    ` ./spatial-index.sh ${v}index_ `
    ` ./draw-doc.sh ${v}draw_ `

    // 16 world units at 400% is 64 screen pixels, scaled back to 16
    match &drawn()[0] {
        Drawn::Text { size, px, .. } => {
            assert_eq!(*px, 64);
            assert!((size - 16.0).abs() < 1e-4);
        }
        other => panic!("{:?}", other),
    }
}

#[test]
fn font_size_comes_from_the_attribute_or_the_style() {
    let svg_text = r#"<svg><text x="10" y="20" font-size="smaller">a</text><text x="10" y="40" style="font-size:10px;">b</text><text x="10" y="60" font-size="24">c</text></svg>"#;
    let canvas = canvas_at(1.0);

    ` ./svg-load.sh ${v}load_ `
    assert_eq!(error, None);
    ` ./spatial-index.sh ${v}index_ `
    ` ./draw-doc.sh ${v}draw_ `

    let sizes: Vec<f32> = drawn()
        .iter()
        .filter_map(|drawn| match drawn {
            Drawn::Text { size, .. } => Some(*size),
            _ => None,
        })
        .collect();
    assert_eq!(sizes.len(), 3);
    assert!((sizes[0] - 16.0 / 1.2).abs() < 1e-3, "{:?}", sizes);
    assert!((sizes[1] - 10.0).abs() < 1e-3, "{:?}", sizes);
    assert!((sizes[2] - 24.0).abs() < 1e-3, "{:?}", sizes);
}

#[test]
fn line_through_strikes_the_text() {
    let svg_text = r#"<svg><text x="55" y="380" fill="black" text-decoration="line-through">abc</text></svg>"#;
    let canvas = canvas_at(1.0);

    ` ./svg-load.sh ${v}load_ `
    assert_eq!(error, None);
    ` ./spatial-index.sh ${v}index_ `
    ` ./draw-doc.sh ${v}draw_ `

    let segments = lines(&drawn());
    assert_eq!(segments.len(), 1);
    let (from, to) = segments[0];
    // across the text, above the baseline
    assert_eq!(from.x, 55.0);
    assert!((to.x - (55.0 + 3.0 * 16.0 * 0.6)).abs() < 1e-3);
    assert!(from.y < 380.0 && from.y > 380.0 - 16.0);
}

