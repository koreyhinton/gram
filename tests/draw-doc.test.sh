#[test]
fn a_rounded_rect_stays_inside_its_box() {
    let svg_text = r#"<svg><rect rx="10" ry="10" x="325" y="112" width="100" height="50" stroke="black" fill="transparent"/></svg>"#;
    let canvas = canvas_at(1.0);

    ` ./svg-load.sh ${v}load_ `
    assert_eq!(error, None);
    ` ./spatial-index.sh ${v}index_ `
    ` ./draw-doc.sh ${v}draw_ `

    let segments = lines(&drawn());
    // the four sides plus the corner arcs
    assert!(segments.len() > 8, "{} segments", segments.len());
    for (from, _) in segments.iter() {
        assert!(from.x >= 325.0 - 1e-3 && from.x <= 425.0 + 1e-3, "{:?}", from);
        assert!(from.y >= 112.0 - 1e-3 && from.y <= 162.0 + 1e-3, "{:?}", from);
    }
    // no point sits on a sharp corner
    let corner = vec2(325.0, 112.0);
    assert!(segments.iter().all(|(from, _)| from.distance(corner) > 2.0));
}

#[test]
fn a_dash_list_of_odd_length_repeats() {
    // "0 10 0" repeats to "0 10 0 0 10 0": nothing, a 10 gap, nothing,
    // then a 10 dash, and again
    let svg_text = r#"<svg><line x1="0" y1="5" x2="40" y2="5" stroke="black" stroke-dasharray="0 10 0"/></svg>"#;
    let canvas = canvas_at(1.0);

    ` ./svg-load.sh ${v}load_ `
    assert_eq!(error, None);
    ` ./spatial-index.sh ${v}index_ `
    ` ./draw-doc.sh ${v}draw_ `

    assert_eq!(
        lines(&drawn()),
        vec![
            (vec2(10.0, 5.0), vec2(20.0, 5.0)),
            (vec2(30.0, 5.0), vec2(40.0, 5.0)),
        ]
    );
}

