#[test]
fn later_elements_draw_over_earlier_ones() {
    // many overlapping squares, so the tree's own order would differ
    let mut svg_text = String::from("<svg>");
    for i in 0..40 {
        svg_text.push_str(&format!(
            r##"<rect x="{}" y="{}" width="30" height="30" fill="#{:06x}"/>"##,
            (i * 37) % 200,
            (i * 53) % 200,
            i + 1
        ));
    }
    svg_text.push_str("</svg>");
    let canvas = canvas_at(1.0);

    ` ./svg-load.sh ${v}load_ `
    assert_eq!(error, None);
    ` ./spatial-index.sh ${v}index_ `
    ` ./draw-doc.sh ${v}draw_ `

    let mut colors = triangles(&drawn());
    colors.dedup();
    let expected: Vec<Color> = (0..40u32)
        .map(|i| Color::from_rgba(0, 0, (i + 1) as u8, 255))
        .collect();
    assert_eq!(colors, expected);
}
