#[test]
fn tdd_20_ctrl_shift_c_copies_the_page() {
    let presses = vec![KeyCode::C];
    let (ctrl, shift) = (true, true);
    ` ./ctrl-keys.sh ${v}ctrl_ `
    assert_eq!(action, Some(CtrlAction::CopyPage));
    // what goes to the clipboard: the page, as a save would write it
    let svg_text = SVG_EX;
    ` ./svg-load.sh ${v}load_ `
