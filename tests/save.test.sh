#[test]
fn a_page_with_no_source_or_an_empty_root_still_writes_whole() {
    // a Doc made in gram: a plain <svg> with its root attributes
    let mut doc = Doc::default();
    doc.root_attrs = vec![("width".to_string(), "750".to_string())];
    ` ./doc-xml.sh ${v}dxml_ `
    assert_eq!(xml, "<svg width=\"750\">\n</svg>\n");

    // an empty <svg/> that gets a line opens up to hold it
    let svg_text = "<svg width=\"10\"/>\n";
    ` ./svg-load.sh ${v}load_ `
    let mut from: Option<Vec2> = None;
    let width = "1";
    for click in [(1.0, 1.0), (1.0, 50.0)] {
        let pos = vec2(click.0, click.1);
        ` ./add-line.sh ${v}line_ `
    }
    ` ./doc-xml.sh ${v}dxml_ `
    assert_eq!(xml, "<svg width=\"10\">\n<line x1=\"1\" y1=\"1\" x2=\"1\" y2=\"50\" stroke=\"black\" stroke-width=\"1\"/>\n</svg>\n");
    let svg_text = xml.clone();
    ` ./svg-load.sh ${v}load_ `
    assert_eq!(error, None);
    assert_eq!(doc.nodes.len(), 1);
}

