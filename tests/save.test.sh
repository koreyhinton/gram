#[test]
fn a_save_replaces_the_file_rather_than_writing_into_it() {
    // a read-only file can't be written into, but a new file renamed over
    // it replaces it: so the save went through <file>.tmp
    let dir = scratch("atomic");
    let path = dir.join("page.svg");
    std::fs::write(&path, "<svg/>").unwrap();
    let mut perms = std::fs::metadata(&path).unwrap().permissions();
    perms.set_readonly(true);
    std::fs::set_permissions(&path, perms).unwrap();
    let xml = SVG_EX.to_string();
    ` ./page-save.sh ${v}save_ `
    assert_eq!(save_error, None);
    assert_eq!(std::fs::read_to_string(&path).unwrap(), SVG_EX);
    assert!(!dir.join("page.svg.tmp").exists());
}

#[test]
fn a_failed_save_says_why_and_leaves_nothing_behind() {
    let dir = scratch("fail");
