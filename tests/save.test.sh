#[test]
fn untouched_files_come_back_byte_for_byte() {
    let root = env!("CARGO_MANIFEST_DIR");
    let mut texts: Vec<(String, String)> = vec![
        ("SVG_EX".to_string(), SVG_EX.to_string()),
        ("HAND_WRITTEN".to_string(), HAND_WRITTEN.to_string()),
        ("empty root".to_string(), "<svg width=\"10\"/>\n".to_string()),
        ("crlf".to_string(), "<svg>\r\n  <rect x=\"1\"/>\r\n</svg>\r\n".to_string()),
    ];
    for dir in ["docs", "docs/examples"] {
        for entry in std::fs::read_dir(format!("{}/{}", root, dir)).unwrap() {
            let path = entry.unwrap().path();
            if path.extension().is_some_and(|ext| ext == "svg") {
                texts.push((path.display().to_string(), std::fs::read_to_string(&path).unwrap()));
            }
        }
    }
    assert!(texts.len() >= 10);
    for (name, svg_text) in texts {
        ` ./svg-load.sh ${v}load_ `
        ` ./mouse-rects.sh ${v}rects_ `
        assert_eq!(error, None, "{}", name);
        ` ./doc-xml.sh ${v}dxml_ `
        assert_eq!(xml, svg_text, "{}", name);
    }
}

#[test]
fn an_edited_node_is_written_fresh_and_the_rest_as_it_was() {
    let svg_text = HAND_WRITTEN;
    ` ./svg-load.sh ${v}load_ `
    // the rect's x 10 -> 15, as an edit in the editor gives it back
    let id = 3;
    assert_eq!(doc.nodes[id].tag, "rect");
    let edit_text = "<svg><rect x='15'/></svg>";
    ` ./svg-load.sh ${v}eload_ `
    ` ./node-apply.sh ${v}apply_ `
    ` ./doc-xml.sh ${v}dxml_ `
    let want = HAND_WRITTEN.replace(
        "<rect x='10'  y='20' width='30' height='40'\n            fill='none'/>",
        "<rect x=\"15\" y=\"20\" width=\"30\" height=\"40\" fill=\"none\"/>",
    );
    assert_ne!(want, HAND_WRITTEN);
    assert_eq!(xml, want);
}

