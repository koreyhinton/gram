    let (ctrl, shift) = (true, false);
    ` ./ctrl-keys.sh ${v}ctrl_ `
    assert_eq!(action, None);
    // and S or C without Ctrl do nothing
    let presses = vec![KeyCode::S, KeyCode::C];
    let (ctrl, shift) = (false, true);
    ` ./ctrl-keys.sh ${v}ctrl_ `
    assert_eq!(action, None);
}

#[test]
fn a_copy_waits_until_the_ctrl_chord_is_let_go() {
    // (pending, ctrl, c, x) -> ready
    let cases = [
        // Ctrl-Shift-C still held: macroquad would overwrite it
        ((true, true, true, false), false),
        // Ctrl and X held (macroquad does the same for cut)
        ((true, true, false, true), false),
        // C let go first, Ctrl still down
        ((true, true, false, false), true),
        // Ctrl let go first, C still down
        ((true, false, true, false), true),
        // all let go
        ((true, false, false, false), true),
        // nothing waiting
        ((false, false, false, false), false),
    ];
    for ((pending, ctrl, c, x), want) in cases {
        ` ./copy-ready.sh ${v}ready_ `
        assert_eq!(ready, want, "pending {} ctrl {} c {} x {}", pending, ctrl, c, x);
    }
}

