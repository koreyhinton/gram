#[test]
fn tdd_19_ctrl_s_saves_the_page() {
    let presses = vec![KeyCode::S];
    let (ctrl, shift) = (true, false);
    ` ./ctrl-keys.sh ${v}ctrl_ `
    assert_eq!(action, Some(CtrlAction::Save));

    // the page, with the rect moved 300 left (edited), saved over its file
    let dir = scratch("save");
    let path = dir.join("act.svg");
    std::fs::write(&path, SVG_EX).unwrap();
    let svg_text = std::fs::read_to_string(&path).unwrap();
    ` ./svg-load.sh ${v}load_ `
    doc.nodes[2].attrs[2].1 = "25".to_string();
    ` ./doc-xml.sh ${v}dxml_ `
    ` ./page-save.sh ${v}save_ `
    assert_eq!(save_error, None);

    // the file is the page (its text at x="333" too), and no .tmp is left
    let saved = std::fs::read_to_string(&path).unwrap();
    assert!(saved.contains(r#"<text x="333" y="134" fill="black">Receive</text>"#));
    assert_eq!(saved, SVG_EX.replace(r#"ry="10" x="325""#, r#"ry="10" x="25""#));
    assert!(!dir.join("act.svg.tmp").exists());
    assert_eq!(std::fs::read_dir(&dir).unwrap().count(), 1);
}

#[test]
fn a_save_keeps_everything_after_a_hex_color() {
