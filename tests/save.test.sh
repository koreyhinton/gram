# Prints the save and copy tests as one Rust file (test.sh writes it to
# tests/save.rs). Step 16 (act.svg@df9a465): the old app's download and copy
# buttons, which gram makes Ctrl-S (save over the page's file) and
# Ctrl-Shift-C (the whole page to the clipboard). Both write the page with
# doc-xml.sh, which gives back an untouched file byte for byte.
#
# The interface these tests fix:
#   svg-load.sh  also keeps the raw source: Doc.head (up to and including
#       <svg ...>), Doc.tail (from </svg> on), and each node's Node.src (the
#       text before it, its start tag, its end tag, and the tag, attributes
#       and text it held).
#   doc-xml.sh  binds Doc and Xml (declared). The page as SVG: unchanged
#       nodes as written, changed ones fresh, new ones on their own line,
#       nesting kept.
#   page-save.sh  binds Path, Xml and Error (declared). Writes <file>.tmp and
#       renames it over the file.
#   ctrl-keys.sh  Ctrl+S is Save, Ctrl+Shift+C is CopyPage; Ctrl+C alone is
#       nothing yet (step 19).
#   copy-ready.sh  binds Pending, Ctrl, C, X and Ready (declared). A copy
#       waits while Ctrl and C or X are down: macroquad's UI overwrites the
#       clipboard with its empty selection on every such frame.
#   hud-hints.sh  binds Dirty: with unsaved changes the hints end with
#       ", Ctrl-S: save".

: "${NSMAP:?set NSMAP (see test.sh)}"

