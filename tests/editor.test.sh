#[test]
fn a_hand_off_editor_round_trip_applies_the_later_save() {
    // `true` stands in for xdg-open: it exits at once and edits nothing
    let path = file_with("handoff-trip", "node.xml", WRITTEN);
    let written = WRITTEN.to_string();
    let editor = "true";
    ` ./editor-open.sh ${v}open_ `
    let started = std::time::Instant::now();
    let mut stamp: Option<(std::time::SystemTime, u64)> = None;
    let mut watching = false;
    let mut outcome = NodeEditOutcome::Wait;

    // frames until the editor exits; the file's stamp is kept every frame
    let mut seen_exit = false;
    for _ in 0..500 {
        ` ./editor-poll.sh ${v}poll_ `
        ` ./file-watch.sh ${v}watch_ `
        let saved = changed;
        let elapsed = started.elapsed().as_secs_f64();
        ` ./node-edit-check.sh ${v}check_ `
        if exited {
            seen_exit = true;
            break;
        }
        std::thread::sleep(std::time::Duration::from_millis(5));
    }
    assert!(seen_exit);
    assert_eq!(outcome, NodeEditOutcome::Wait);
    assert!(watching);

    // the person saves in the text editor a moment later
    std::thread::sleep(std::time::Duration::from_millis(20));
    std::fs::write(&path, r#"<rect x="400" y="112"/>"#).unwrap();
    let exited = false;
    ` ./file-watch.sh ${v}watch_ `
    let saved = changed;
    let elapsed = started.elapsed().as_secs_f64();
    ` ./node-edit-check.sh ${v}check_ `
    assert_eq!(outcome, NodeEditOutcome::Apply(r#"<rect x="400" y="112"/>"#.to_string()));
}

