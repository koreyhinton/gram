#!/bin/bash

# Prints the external editor tests as one Rust file (test.sh writes it to
# tests/editor.rs). The editor is a real process: sed -i stands in for a
# person, as CLAUDE.md says, so a round trip runs without anyone at the
# keyboard. Files live in a fresh folder under the system temp folder.
#
# The interface these tests fix:
#   editor-pick.sh  binds Editor: $GRAM_EDITOR, then $VISUAL, then $EDITOR
#       (blank ones skipped), else xdg-open.
#   editor-open.sh  binds Editor, Path, Child and Error. Starts the command
#       through sh with the file as its last argument, without waiting.
#   editor-poll.sh  binds Child, Exited and Failed. try_wait: Exited on the
#       frame the editor exits (Child becomes None), Failed when it exits
#       unsuccessfully.
#   file-watch.sh   binds Path, Stamp and Changed. Changed when the file's
#       modified time or length moved since the last stamp.
#   edit-escape.sh  binds Pressed, Now, WarnedAt and Drop, for Esc while an
#       edit is open. The first Esc sets WarnedAt to Now (the banner then
#       asks for a second); another Esc within DROP_CONFIRM_SECS (3) of it
#       sets Drop (declared here) and clears WarnedAt; a later one only warns
#       again. A frame without Esc changes nothing.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}pick_Editor=editor
export ${v}open_Editor=editor
export ${v}open_Path=path.as_path\(\)
export ${v}open_Child=child
export ${v}open_Error=error
export ${v}poll_Child=child
export ${v}poll_Exited=exited
export ${v}poll_Failed=failed
export ${v}watch_Path=path.as_path\(\)
export ${v}watch_Stamp=stamp
export ${v}watch_Changed=changed
export ${v}esc_Pressed=pressed
export ${v}esc_Now=now
export ${v}esc_WarnedAt=warned_at
export ${v}esc_Drop=drop_edit

cat << EOF
// Code generated by tests/editor.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]
// a test reads only the outputs it checks
#![allow(unused_variables, unused_assignments, unused_mut)]

use macroquad::prelude::*;
use std::path::PathBuf;

EOF

# the app's constants and types
./models.sh

cat << EOF

// a fresh folder for one test, with one file in it
fn file_with(test: &str, name: &str, text: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("gram-test-{}-{}", std::process::id(), test));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join(name);
    std::fs::write(&path, text).unwrap();
    path
}

#[test]
fn the_editor_comes_from_gram_editor_then_visual_then_editor() {
    // the only test that touches these variables, so tests running at the
    // same time don't see them change
    unsafe {
        std::env::set_var("GRAM_EDITOR", "gram-ed");
        std::env::set_var("VISUAL", "visual-ed");
        std::env::set_var("EDITOR", "editor-ed");
    }
    ` ./editor-pick.sh ${v}pick_ `
    assert_eq!(editor, "gram-ed");

    unsafe { std::env::set_var("GRAM_EDITOR", "  ") };
    ` ./editor-pick.sh ${v}pick_ `
    assert_eq!(editor, "visual-ed");

    unsafe { std::env::remove_var("VISUAL") };
    ` ./editor-pick.sh ${v}pick_ `
    assert_eq!(editor, "editor-ed");

    unsafe {
        std::env::remove_var("EDITOR");
        std::env::remove_var("GRAM_EDITOR");
    }
    ` ./editor-pick.sh ${v}pick_ `
    assert_eq!(editor, "xdg-open");
}

#[test]
fn an_editor_edits_the_file_and_is_seen_to_exit() {
    // a path with a space, so the file stays one argument
    let path = file_with("open", "node one.svg", r#"<rect x="325" y="112"/>"#);
    let editor = "sed -i s/325/25/";

    ` ./editor-open.sh ${v}open_ `
    assert_eq!(error, None);
    assert!(child.is_some());

    // poll as the frame loop would, until it exits
    let mut seen_exit = false;
    let mut polls = 0;
    while !seen_exit && polls < 500 {
        ` ./editor-poll.sh ${v}poll_ `
        seen_exit = exited;
        assert_eq!(failed, None);
        if !seen_exit {
            std::thread::sleep(std::time::Duration::from_millis(10));
        }
        polls += 1;
    }
    assert!(seen_exit, "the editor never exited");
    assert!(child.is_none());
    assert_eq!(std::fs::read_to_string(&path).unwrap(), r#"<rect x="25" y="112"/>"#);

    // polling after the exit reports nothing more
    ` ./editor-poll.sh ${v}poll_ `
    assert!(!exited);
}

#[test]
fn an_editor_that_fails_says_so() {
    let path = file_with("fail", "node.xml", "<rect/>");
    let editor = "gram-test-no-such-editor";

    ` ./editor-open.sh ${v}open_ `
    assert_eq!(error, None);

    let mut seen_exit = false;
    let mut reason: Option<String> = None;
    let mut polls = 0;
    while !seen_exit && polls < 500 {
        ` ./editor-poll.sh ${v}poll_ `
        seen_exit = exited;
        reason = failed;
        if !seen_exit {
            std::thread::sleep(std::time::Duration::from_millis(10));
        }
        polls += 1;
    }
    assert!(seen_exit);
    // sh exits 127 for a command it can't find
    assert!(reason.as_deref().is_some_and(|text| text.contains("127")), "{:?}", reason);
}

#[test]
fn a_save_is_seen_once() {
    let path = file_with("watch", "page.svg", "<svg></svg>");
    let mut stamp: Option<(std::time::SystemTime, u64)> = None;

    // the first look takes the stamp
    ` ./file-watch.sh ${v}watch_ `
    assert!(changed);
    ` ./file-watch.sh ${v}watch_ `
    assert!(!changed);

    // a save that changes only the length: the modified time is put back
    let before = stamp.unwrap().0;
    std::fs::write(&path, "<svg><rect/></svg>").unwrap();
    std::fs::File::options().write(true).open(&path).unwrap().set_modified(before).unwrap();
    ` ./file-watch.sh ${v}watch_ `
    assert!(changed);
    ` ./file-watch.sh ${v}watch_ `
    assert!(!changed);

    // a save of the same length, a moment later
    let later = std::time::SystemTime::now() + std::time::Duration::from_secs(5);
    std::fs::write(&path, "<svg><line/></svg>").unwrap();
    std::fs::File::options().write(true).open(&path).unwrap().set_modified(later).unwrap();
    ` ./file-watch.sh ${v}watch_ `
    assert!(changed);

    // a file that's gone
    std::fs::remove_file(&path).unwrap();
    ` ./file-watch.sh ${v}watch_ `
    assert!(changed);
    assert_eq!(stamp, None);
}

// ---- Esc twice drops an open edit (step 6) ----

#[test]
fn esc_twice_drops_an_open_edit() {
    let mut warned_at: Option<f64> = None;
    // (declared by edit-escape.sh; here too, so a missing snippet fails, not breaks the build)
    let mut drop_edit = false;

    // no Esc: nothing
    let (pressed, now) = (false, 10.0);
    ` ./edit-escape.sh ${v}esc_ `
    assert!(!drop_edit);
    assert_eq!(warned_at, None);

    // the first Esc only warns
    let (pressed, now) = (true, 10.0);
    ` ./edit-escape.sh ${v}esc_ `
    assert!(!drop_edit);
    assert_eq!(warned_at, Some(10.0));

    // a frame without Esc keeps the warning
    let (pressed, now) = (false, 11.0);
    ` ./edit-escape.sh ${v}esc_ `
    assert!(!drop_edit);
    assert_eq!(warned_at, Some(10.0));

    // the second, within the window, drops the edit
    let (pressed, now) = (true, 11.5);
    ` ./edit-escape.sh ${v}esc_ `
    assert!(drop_edit);
    assert_eq!(warned_at, None);
}

#[test]
fn a_second_esc_too_late_only_warns_again() {
    let mut warned_at: Option<f64> = None;
    let mut drop_edit = false;

    let (pressed, now) = (true, 10.0);
    ` ./edit-escape.sh ${v}esc_ `
    let (pressed, now) = (true, 20.0);
    ` ./edit-escape.sh ${v}esc_ `

    assert!(!drop_edit);
    assert_eq!(warned_at, Some(20.0));
}

