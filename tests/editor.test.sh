#!/bin/bash

# Prints the external editor tests as one Rust file (test.sh writes it to
# tests/editor.rs). The editor is a real process: sed -i stands in for a
# person, as CLAUDE.md says, so a round trip runs without anyone at the
# keyboard. Files live in a fresh folder under the system temp folder.
#
# The interface these tests fix:
#   editor-pick.sh  binds Editor: $GRAM_EDITOR, then $VISUAL, then $EDITOR
#       (blank ones skipped), else xdg-open.
#   editor-open.sh  binds Editor, Path, Child and Error. Starts the command
#       through sh with the file as its last argument, without waiting.
#   editor-poll.sh  binds Child, Exited and Failed. try_wait: Exited on the
#       frame the editor exits (Child becomes None), Failed when it exits
#       unsuccessfully.
#   file-watch.sh   binds Path, Stamp and Changed. Changed when the file's
#       modified time or length moved since the last stamp.
#   edit-escape.sh  binds Pressed, Now, WarnedAt and Drop, for Esc while an
#       edit is open. The first Esc sets WarnedAt to Now (the banner then
#       asks for a second); another Esc within DROP_CONFIRM_SECS (3) of it
#       sets Drop (declared here) and clears WarnedAt; a later one only warns
#       again. A frame without Esc changes nothing.
#   node-edit-check.sh  binds Path, Written, Exited, Elapsed, Saved, Watching
#       and Outcome: what a node edit's file says this frame. When the editor
#       exits with the file changed: Apply(text); unchanged: Unchanged, unless
#       it exited within HANDOFF_SECS of starting (xdg-open, a text editor that
#       was handed the file): then Watching is set and the edit stays open, and
#       the first save (Saved, from file-watch.sh) that changes the file is
#       Apply(text). An unreadable file is Failed. Otherwise Wait.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}pick_Editor=editor
export ${v}open_Editor=editor
export ${v}open_Path=path.as_path\(\)
export ${v}open_Child=child
export ${v}open_Error=error
export ${v}poll_Child=child
export ${v}poll_Exited=exited
export ${v}poll_Failed=failed
export ${v}watch_Path=path.as_path\(\)
export ${v}watch_Stamp=stamp
export ${v}watch_Changed=changed
export ${v}esc_Pressed=pressed
export ${v}esc_Now=now
export ${v}esc_WarnedAt=warned_at
export ${v}esc_Drop=drop_edit
export ${v}check_Path=path.as_path\(\)
export ${v}check_Written=written.as_str\(\)
export ${v}check_Exited=exited
export ${v}check_Elapsed=elapsed
export ${v}check_Saved=saved
export ${v}check_Watching=watching
export ${v}check_Outcome=outcome

cat << EOF
// Code generated by tests/editor.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]
// a test reads only the outputs it checks
#![allow(unused_variables, unused_assignments, unused_mut)]

use macroquad::prelude::*;
use std::path::PathBuf;

EOF

# the app's constants and types
./models.sh

