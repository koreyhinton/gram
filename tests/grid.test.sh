#!/bin/bash

# Prints the grid tests as one Rust file (test.sh writes it to
# tests/grid.rs). They draw the grid once (draw-grid.sh) with draw_line and
# the screen size stubbed, and check the lines it drew.
#
# The interface these tests fix:
#   draw-grid.sh  binds Canvas. It draws a major level, GRID_SUBDIVS times the
#       spacing that is GRID_MIN_PX on screen, and the minor level between,
#       faded by how close its lines are; one screen pixel thick at any zoom
#       (major 1.25); lines through the origin in GRID_AXIS.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}grid_Canvas=canvas

cat << EOF
// Code generated by tests/grid.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]

use macroquad::prelude::*;
use std::cell::RefCell;

EOF

# the app's constants and types
./models.sh

cat << EOF

#[derive(Debug, Clone, Copy, PartialEq)]
struct Line {
    from: Vec2,
    to: Vec2,
    thickness: f32,
    color: Color,
}

thread_local! {
    static LINES: RefCell<Vec<Line>> = RefCell::new(Vec::new());
}

fn draw_line(x1: f32, y1: f32, x2: f32, y2: f32, thickness: f32, color: Color) {
    LINES.with(|lines| lines.borrow_mut().push(Line { from: vec2(x1, y1), to: vec2(x2, y2), thickness, color }));
}

fn lines() -> Vec<Line> {
    LINES.with(|lines| lines.borrow_mut().drain(..).collect())
}

// a 1000x1000 screen
fn screen_width() -> f32 {
    1000.0
}

fn screen_height() -> f32 {
    1000.0
}

// the x of each vertical line drawn this thick
fn verticals(lines: &[Line], thickness: f32) -> Vec<f32> {
    lines
        .iter()
        .filter(|line| line.from.x == line.to.x && (line.thickness - thickness).abs() < 1e-5)
        .map(|line| line.from.x)
        .collect()
}

#[test]
fn at_full_size_the_minor_grid_is_25_and_the_major_125() {
    // log5(35) = 2.2: level 2, so minor lines every 25, major every 125
    let canvas = Canvas { offset: vec2(10.0, 10.0), zoom: 1.0, panning: false, last_mouse: Vec2::ZERO };

    ` ./draw-grid.sh ${v}grid_ `

    let drawn = lines();
    let minor = verticals(&drawn, 1.0);
    let major = verticals(&drawn, 1.25);
    assert_eq!(minor.first(), Some(&0.0));
    assert!(minor.windows(2).all(|pair| (pair[1] - pair[0] - 25.0).abs() < 1e-3), "{:?}", minor);
    assert!(major.windows(2).all(|pair| (pair[1] - pair[0] - 125.0).abs() < 1e-3), "{:?}", major);
    // they cover the view, 10..1010
    assert!(*minor.last().unwrap() > 1010.0 - 25.0);
    // the minor level is part faded: 1 - 0.209
    let minor_alpha = drawn.iter().find(|line| line.thickness == 1.0).unwrap().color.a;
    let fade = 1.0 - (35.0f32.log(5.0) - 2.0);
    assert!((minor_alpha - GRID_MINOR.a * fade).abs() < 1e-4);
}

#[test]
fn lines_stay_one_screen_pixel_thick_when_zoomed() {
    let canvas = Canvas { offset: vec2(0.0, 0.0), zoom: 4.0, panning: false, last_mouse: Vec2::ZERO };

    ` ./draw-grid.sh ${v}grid_ `

    let drawn = lines();
    assert!(!verticals(&drawn, 1.0 / 4.0).is_empty());
    assert!(!verticals(&drawn, 1.25 / 4.0).is_empty());
}

#[test]
fn the_minor_grid_goes_when_it_has_faded_out() {
    // just short of the next level: 99% of the way, so 1% faded in
    let zoom = 35.0 / 5.0f32.powf(2.99);
    let canvas = Canvas { offset: vec2(0.0, 0.0), zoom, panning: false, last_mouse: Vec2::ZERO };

    ` ./draw-grid.sh ${v}grid_ `

    let drawn = lines();
    assert!(drawn.iter().all(|line| line.color == GRID_MAJOR || line.color == GRID_AXIS));
}

#[test]
fn the_origin_axes_are_drawn_darker() {
    let canvas = Canvas { offset: vec2(-500.0, -500.0), zoom: 1.0, panning: false, last_mouse: Vec2::ZERO };

    ` ./draw-grid.sh ${v}grid_ `

    let axes: Vec<Line> = lines().into_iter().filter(|line| line.color == GRID_AXIS).collect();
    assert_eq!(axes.len(), 2);
    assert!(axes.iter().any(|line| line.from.x == 0.0 && line.to.x == 0.0));
    assert!(axes.iter().any(|line| line.from.y == 0.0 && line.to.y == 0.0));
}

#[test]
fn the_grid_only_covers_the_view() {
    let canvas = Canvas { offset: vec2(1e6, 1e6), zoom: 1.0, panning: false, last_mouse: Vec2::ZERO };

    ` ./draw-grid.sh ${v}grid_ `

    let drawn = lines();
    // 1000 / 25 + 1 minor lines each way, plus the major ones over them
    assert!(drawn.len() <= 2 * (41 + 9), "{} lines", drawn.len());
    assert!(drawn.iter().all(|line| line.from.x >= 1e6 - 25.0 && line.from.y >= 1e6 - 25.0));
}
EOF
