// TDD TEST 2 - MODE TWO CLICK TWICE CREATES LINE (key 1, "1 => Line Mode")
#[test]
fn tdd_02_line_mode_two_clicks_create_a_line() {
    let svg_text = SVG_EX;
    ` ./svg-load.sh ${v}load_ `
    let mut from: Option<Vec2> = None;

    // the first click only starts the line
    let pos = vec2(25.0, 25.0);
    ` ./add-line.sh ${v}line_ `
    assert_eq!(from, Some(vec2(25.0, 25.0)));
    assert_eq!(doc.nodes.len(), 5);

    // the second ends it
    let y_expect = 519.0;
    let pos = vec2(25.0, y_expect);
    ` ./add-line.sh ${v}line_ `
    assert_eq!(from, None);
    assert_eq!(doc.nodes.len(), 6);
    let id = 5;
    ` ./node-xml.sh ${v}xml_ `
    assert_eq!(xml, r#"<line x1="25" y1="25" x2="25" y2="519" stroke="black" stroke-width="1"/>"#);
}

#[test]
fn a_drawn_line_can_be_clicked() {
    let svg_text = SVG_EX;
    ` ./svg-load.sh ${v}load_ `
    let mut from: Option<Vec2> = None;
    for click in [(25.0, 25.0), (25.0, 519.0)] {
        let pos = vec2(click.0, click.1);
        ` ./add-line.sh ${v}line_ `
    }
    ` ./mouse-rects.sh ${v}rects_ `
