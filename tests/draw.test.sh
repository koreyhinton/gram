#!/bin/bash

# Prints the drawing-mode tests as one Rust file (test.sh writes it to
# tests/draw.rs). They follow the old web app's line mode (devbox@ed1a227):
# with key 1 down, a click starts a line and the next click ends it.
#
# The interface these tests fix:
#   draw-line.sh  binds Nodes, Pos and From. Pos is the click in world
#       units; From (Option<Vec2>, declared by the caller) is the first
#       click, still waiting for its end. A first click sets From; the
#       second appends <line x1 y1 x2 y2 stroke="black" stroke-width="1"/>
#       (ends rounded to whole numbers, as the browser's clicks were) and
#       clears From. The caller marks the page dirty and rebuilds the
#       click boxes when Nodes grew.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}load_Text=svg_text
export ${v}load_Doc=doc
export ${v}load_Error=error
export ${v}rects_Nodes=doc.nodes
export ${v}index_Doc=doc
export ${v}index_Index=index
export ${v}hit_Doc=doc
export ${v}hit_Index=index
export ${v}hit_Pos=pos
export ${v}hit_Hit=hit
export ${v}line_Nodes=doc.nodes
export ${v}line_Pos=pos
export ${v}line_From=from
export ${v}xml_Node=\(\&doc.nodes[id]\)
export ${v}xml_Xml=xml

cat << EOF
// Code generated by tests/draw.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]
// a test reads only the outputs it checks
#![allow(unused_variables, unused_assignments, unused_mut)]

use macroquad::prelude::*;

EOF

# the app's constants and types
./models.sh

cat << EOF

// the old web app's example drawing (svgEx in devbox@ed1a227)
const SVG_EX: &str = r#"<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="750" height="750" viewBox="0,0,750,750">
    <circle cx="375" cy="40" r="10" stroke="black" stroke-width="1"/>
    <polyline points="375 52 375 110 365 100 375 110 385 100" stroke="black" fill="transparent" stroke-width="1"/>
    <rect rx="10" ry="10" x="325" y="112" width="100" height="50" stroke="black" fill="transparent" stroke-width="1"/>
    <text x="333" y="134" fill="black">Receive</text>
    <text x="333" y="154" fill="black">Request</text>
</svg>"#;

// TDD TEST 2 - MODE TWO CLICK TWICE CREATES LINE (key 1, "1 => Line Mode")
#[test]
fn tdd_02_line_mode_two_clicks_create_a_line() {
    let svg_text = SVG_EX;
    ` ./svg-load.sh ${v}load_ `
    let mut from: Option<Vec2> = None;

    // the first click only starts the line
    let pos = vec2(25.0, 25.0);
    ` ./draw-line.sh ${v}line_ `
    assert_eq!(from, Some(vec2(25.0, 25.0)));
    assert_eq!(doc.nodes.len(), 5);

    // the second ends it
    let y_expect = 519.0;
    let pos = vec2(25.0, y_expect);
    ` ./draw-line.sh ${v}line_ `
    assert_eq!(from, None);
    assert_eq!(doc.nodes.len(), 6);
    let id = 5;
    ` ./node-xml.sh ${v}xml_ `
    assert_eq!(xml, r#"<line x1="25" y1="25" x2="25" y2="519" stroke="black" stroke-width="1"/>"#);
}

#[test]
fn a_drawn_line_can_be_clicked() {
    let svg_text = SVG_EX;
    ` ./svg-load.sh ${v}load_ `
    let mut from: Option<Vec2> = None;
    for click in [(25.0, 25.0), (25.0, 519.0)] {
        let pos = vec2(click.0, click.1);
        ` ./draw-line.sh ${v}line_ `
    }
    ` ./mouse-rects.sh ${v}rects_ `
    ` ./spatial-index.sh ${v}index_ `

    let pos = vec2(25.0, 300.0);
    ` ./hit-test.sh ${v}hit_ `
    assert_eq!(hit, Some(5));
    // at the top level, not inside anything
    assert_eq!(doc.nodes[5].parent, None);
}

#[test]
fn a_line_ends_on_whole_numbers() {
    // zoomed in, a click lands between world units
    let svg_text = r#"<svg></svg>"#;
    ` ./svg-load.sh ${v}load_ `
    let mut from: Option<Vec2> = None;
    for click in [(10.4, 20.6), (30.5, 40.49)] {
        let pos = vec2(click.0, click.1);
        ` ./draw-line.sh ${v}line_ `
    }
    let id = 0;
    ` ./node-xml.sh ${v}xml_ `
    assert_eq!(xml, r#"<line x1="10" y1="21" x2="31" y2="40" stroke="black" stroke-width="1"/>"#);
}

#[test]
fn each_pair_of_clicks_draws_its_own_line() {
    let svg_text = r#"<svg></svg>"#;
    ` ./svg-load.sh ${v}load_ `
    let mut from: Option<Vec2> = None;
    for click in [(0.0, 0.0), (10.0, 0.0), (20.0, 5.0), (20.0, 15.0)] {
        let pos = vec2(click.0, click.1);
        ` ./draw-line.sh ${v}line_ `
    }
    assert_eq!(doc.nodes.len(), 2);
    assert_eq!(from, None);
    let id = 1;
    ` ./node-xml.sh ${v}xml_ `
    assert_eq!(xml, r#"<line x1="20" y1="5" x2="20" y2="15" stroke="black" stroke-width="1"/>"#);
}
EOF
