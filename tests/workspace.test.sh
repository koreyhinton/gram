#[test]
fn the_tree_lists_folders_first_by_name_ignoring_case() {
    let root = folder_with(
        "scan-order",
        // C.svg sorts after b.svg only when case is ignored
        &["b.svg", "C.svg", "A.svg", "zeta/c.svg", "Alpha/d.svg", "Alpha/sub/e.svg"],
    );

    ` ./tree-scan.sh ${v}scan_ `

    assert_eq!(
        rows(&entries),
        vec![
            row("Alpha", 0, true),
            row("sub", 1, true),
            row("e.svg", 2, false),
            row("d.svg", 1, false),
            row("zeta", 0, true),
            row("c.svg", 1, false),
            row("A.svg", 0, false),
            row("b.svg", 0, false),
            row("C.svg", 0, false),
        ]
    );
    assert_eq!(entries[2].path, root.join("Alpha/sub/e.svg"));
}

