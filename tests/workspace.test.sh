// ---- folders on disk ----

// a fresh folder for one test, holding these files (a name ending in /
// makes an empty folder)
fn folder_with(test: &str, files: &[&str]) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("gram-test-{}-{}", std::process::id(), test));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    for file in files {
        let path = dir.join(file);
        if file.ends_with('/') {
            std::fs::create_dir_all(&path).unwrap();
        } else {
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, "<svg></svg>").unwrap();
        }
    }
    std::fs::canonicalize(dir).unwrap()
}

// (name, depth, is a folder) for each entry
fn rows(entries: &[TreeEntry]) -> Vec<(String, usize, bool)> {
    entries.iter().map(|entry| (entry.name.clone(), entry.depth, entry.is_dir)).collect()
}

fn row(name: &str, depth: usize, is_dir: bool) -> (String, usize, bool) {
    (name.to_string(), depth, is_dir)
}

// ---- the stubbed mouse, screen and drawing ----

#[derive(Clone, Copy, Default)]
struct Input {
    mouse: (f32, f32),
    pressed: bool,
    wheel: f32,
}

#[derive(Debug, Clone, PartialEq)]
enum Drawn {
    Rect { rect: Rect, color: Color },
    Text { text: String, x: f32, y: f32, color: Color },
}

thread_local! {
    static INPUT: RefCell<Input> = RefCell::new(Input::default());
    static DRAWN: RefCell<Vec<Drawn>> = RefCell::new(Vec::new());
}

fn set_input(input: Input) {
    INPUT.with(|state| *state.borrow_mut() = input);
}

fn input() -> Input {
    INPUT.with(|state| *state.borrow())
}

fn drawn() -> Vec<Drawn> {
    DRAWN.with(|list| list.borrow_mut().drain(..).collect())
}

fn texts(list: &[Drawn]) -> Vec<(String, f32, Color)> {
    list.iter()
        .filter_map(|drawn| match drawn {
            Drawn::Text { text, x, color, .. } => Some((text.clone(), *x, *color)),
            _ => None,
        })
        .collect()
}

fn mouse_position() -> (f32, f32) {
    input().mouse
}

fn is_mouse_button_pressed(button: MouseButton) -> bool {
    button == MouseButton::Left && input().pressed
}

fn mouse_wheel() -> (f32, f32) {
    (0.0, input().wheel)
}

fn screen_height() -> f32 {
    300.0
}

fn draw_rectangle(x: f32, y: f32, w: f32, h: f32, color: Color) {
    DRAWN.with(|list| list.borrow_mut().push(Drawn::Rect { rect: Rect::new(x, y, w, h), color }));
}

fn draw_line(_x1: f32, _y1: f32, _x2: f32, _y2: f32, _thickness: f32, _color: Color) {}

fn draw_rectangle_lines(_x: f32, _y: f32, _w: f32, _h: f32, _thickness: f32, _color: Color) {}

fn draw_text_ex(text: &str, x: f32, y: f32, params: TextParams) {
    DRAWN.with(|list| {
        list.borrow_mut().push(Drawn::Text { text: text.to_string(), x, y, color: params.color })
    });
}

fn draw_text(text: &str, x: f32, y: f32, _font_size: f32, color: Color) {
    DRAWN.with(|list| list.borrow_mut().push(Drawn::Text { text: text.to_string(), x, y, color }));
}

// a stand-in width: 0.6em per character
fn measure_text(text: &str, _font: Option<&Font>, font_size: u16, font_scale: f32) -> TextDimensions {
    TextDimensions {
        width: text.chars().count() as f32 * font_size as f32 * font_scale * 0.6,
        height: font_size as f32 * font_scale,
        offset_y: font_size as f32 * font_scale,
    }
}

// a tree by hand: (name, depth, is a folder), with paths under /t
fn tree(list: &[(&str, usize, bool)]) -> Vec<TreeEntry> {
    let mut parents: Vec<PathBuf> = vec![PathBuf::from("/t")];
    let mut entries = vec![];
    for (name, depth, is_dir) in list {
        parents.truncate(depth + 1);
        let path = parents[*depth].join(name);
        if *is_dir {
            parents.push(path.clone());
        }
        entries.push(TreeEntry { path, name: name.to_string(), depth: *depth, is_dir: *is_dir });
    }
    entries
}

// the screen point in the middle of a shown row
fn row_at(index: usize) -> (f32, f32) {
    (40.0, TREE_PAD + index as f32 * TREE_ROW_H + TREE_ROW_H / 2.0)
}

fn page(path: &str, dirty: bool, error: Option<&str>) -> Page {
    Page {
        path: PathBuf::from(path),
        doc: Doc::default(),
        index: rstar::RTree::new(),
        canvas: Canvas { offset: Vec2::ZERO, zoom: 1.0, panning: false, last_mouse: Vec2::ZERO },
        error: error.map(|err| err.to_string()),
        dirty,
        fitted: false,
        selection: Selection::default(),
        line_from: None,
    }
}

