#[test]
fn a_long_name_is_cut_short_to_fit_the_panel() {
    let long = format!("{}.svg", "x".repeat(60));
    let entries = tree(&[("deep", 0, true), (long.as_str(), 1, false)]);
    let collapsed: Vec<PathBuf> = vec![];
    let scroll = 0.0f32;
    let pages: Vec<Page> = vec![];
    let selected: Option<&Path> = None;

    ` ./tree-draw.sh ${v}tree_ `

    let list = texts(&drawn());
    let (text, x, _) = &list[1];
    assert!(text.ends_with('…'), "{}", text);
    assert!(text.starts_with("xxx"), "{}", text);
    let width = measure_text(text, None, TREE_TEXT_PX, 1.0).width;
    assert!(x + width <= TREE_W - TREE_PAD, "{} ends at {}", text, x + width);
}

