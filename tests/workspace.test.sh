#[test]
fn a_folder_opens_with_nothing_selected() {
    let dir = folder_with("args-folder", &["a.svg"]);
    let arg = dir.to_str().unwrap();

    ` ./workspace-args.sh ${v}args_ `

    assert_eq!(error, None);
    assert_eq!(root, dir);
    assert_eq!(open, None);
}

#[test]
fn an_svg_file_opens_its_folder_with_it_selected() {
    let dir = folder_with("args-file", &["sub/act.SVG"]);
    let file = dir.join("sub/act.SVG");
    let arg = file.to_str().unwrap();

    ` ./workspace-args.sh ${v}args_ `

    assert_eq!(error, None);
    assert_eq!(root, dir.join("sub"));
    assert_eq!(open, Some(file));
}

#[test]
fn other_files_and_missing_paths_are_errors() {
    let dir = folder_with("args-bad", &["notes.txt"]);
    let notes = dir.join("notes.txt");
    let arg = notes.to_str().unwrap();

    ` ./workspace-args.sh ${v}args_ `

    assert_eq!(error, Some("not a folder or an .svg file".to_string()));
    assert_eq!(open, None);

    let missing = dir.join("missing.svg");
    let arg = missing.to_str().unwrap();

    ` ./workspace-args.sh ${v}args_ `

    assert!(error.is_some());
    assert_eq!(open, None);
}

