#[test]
fn rows_are_indented_with_fold_marks_and_the_open_page_highlighted() {
    let entries = tree(&[
        ("docs", 0, true),
        ("a.svg", 1, false),
        ("old", 0, true),
        ("hidden.svg", 1, false),
        ("b.svg", 0, false),
    ]);
    let collapsed = vec![PathBuf::from("/t/old")];
    let scroll = 0.0f32;
    let pages: Vec<Page> = vec![];
    let selected: Option<&Path> = Some(Path::new("/t/b.svg"));

    ` ./tree-draw.sh ${v}tree_ `

    let list = drawn();
    assert_eq!(
        texts(&list).iter().map(|(text, x, _)| (text.as_str(), *x)).collect::<Vec<_>>(),
        vec![
            ("- docs", TREE_PAD),
            ("a.svg", TREE_PAD + TREE_INDENT),
            ("+ old", TREE_PAD),
            ("b.svg", TREE_PAD),
            (TREE_BUTTON_LABEL, TREE_W - TREE_BUTTON_W + 7.0),
        ]
    );
    // b.svg is the fourth row shown
    assert!(list.contains(&Drawn::Rect {
        rect: Rect::new(0.0, TREE_PAD + 3.0 * TREE_ROW_H, TREE_W, TREE_ROW_H),
        color: TREE_SELECTED,
    }));
}

#[test]
fn a_changed_page_has_a_star_and_a_failed_one_is_red() {
