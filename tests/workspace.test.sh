#[test]
fn the_wheel_scrolls_the_tree_within_its_rows() {
    let names: Vec<String> = (0..40).map(|i| format!("{:02}.svg", i)).collect();
    let list: Vec<(&str, usize, bool)> = names.iter().map(|name| (name.as_str(), 0, false)).collect();
    let entries = tree(&list);
    let mut collapsed: Vec<PathBuf> = vec![];
    let mut scroll = 0.0f32;

    // down a notch, then click the top row shown
    set_input(Input { mouse: row_at(0), wheel: -1.0, ..Default::default() });
    ` ./tree-click.sh ${v}click_ `
    assert_eq!(scroll, TREE_SCROLL_ROWS * TREE_ROW_H);
    set_input(Input { mouse: row_at(0), pressed: true, ..Default::default() });
    ` ./tree-click.sh ${v}click_ `
    assert_eq!(clicked, Some(PathBuf::from(format!("/t/{:02}.svg", TREE_SCROLL_ROWS as usize))));

    // far down stops at the last row; far up stops at the top
    let last = 40.0 * TREE_ROW_H + 2.0 * TREE_PAD - screen_height();
    for _ in 0..50 {
        set_input(Input { mouse: row_at(0), wheel: -1.0, ..Default::default() });
        ` ./tree-click.sh ${v}click_ `
    }
    assert_eq!(scroll, last);
    for _ in 0..50 {
        set_input(Input { mouse: row_at(0), wheel: 1.0, ..Default::default() });
        ` ./tree-click.sh ${v}click_ `
    }
    assert_eq!(scroll, 0.0);

    // off the panel, the wheel is the canvas's
    set_input(Input { mouse: (TREE_W + 1.0, 10.0), wheel: -1.0, ..Default::default() });
    ` ./tree-click.sh ${v}click_ `
    assert_eq!(scroll, 0.0);
}

#[test]
fn the_open_pages_edit_button_reports_an_edit_not_an_open() {
    let entries = tree(&[("a.svg", 0, false), ("b.svg", 0, false)]);
    let mut collapsed: Vec<PathBuf> = vec![];
    let mut scroll = 0.0f32;
    let selected: Option<&Path> = Some(Path::new("/t/b.svg"));

    // the button at the end of the open page's row
    set_input(Input { mouse: (TREE_W - 10.0, row_at(1).1), pressed: true, ..Default::default() });
    ` ./tree-click.sh ${v}clicksel_ `
    assert!(edit_file);
    assert_eq!(clicked, None);

    // the same place on another row opens that file
    set_input(Input { mouse: (TREE_W - 10.0, row_at(0).1), pressed: true, ..Default::default() });
    ` ./tree-click.sh ${v}clicksel_ `
    assert!(!edit_file);
    assert_eq!(clicked, Some(PathBuf::from("/t/a.svg")));

    // the open page's name, left of the button, opens it as before
    set_input(Input { mouse: row_at(1), pressed: true, ..Default::default() });
    ` ./tree-click.sh ${v}clicksel_ `
    assert!(!edit_file);
    assert_eq!(clicked, Some(PathBuf::from("/t/b.svg")));
}

