#[test]
fn clicking_a_folder_folds_it_and_hides_its_rows_then_unfolds_it() {
    let entries = tree(&[
        ("docs", 0, true),
        ("deep", 1, true),
        ("a.svg", 2, false),
        ("b.svg", 1, false),
        ("c.svg", 0, false),
    ]);
    let mut collapsed: Vec<PathBuf> = vec![];
    let mut scroll = 0.0f32;

    set_input(Input { mouse: row_at(0), pressed: true, ..Default::default() });
    ` ./tree-click.sh ${v}click_ `
    assert_eq!(clicked, None);
    assert_eq!(collapsed, vec![PathBuf::from("/t/docs")]);

    // folded, the second row is c.svg
    set_input(Input { mouse: row_at(1), pressed: true, ..Default::default() });
    ` ./tree-click.sh ${v}click_ `
    assert_eq!(clicked, Some(PathBuf::from("/t/c.svg")));

    set_input(Input { mouse: row_at(0), pressed: true, ..Default::default() });
    ` ./tree-click.sh ${v}click_ `
    assert_eq!(collapsed, Vec::<PathBuf>::new());

    // unfolded again, the second row is the deep folder
    set_input(Input { mouse: row_at(1), pressed: true, ..Default::default() });
    ` ./tree-click.sh ${v}click_ `
    assert_eq!(clicked, None);
    assert_eq!(collapsed, vec![PathBuf::from("/t/docs/deep")]);
}

