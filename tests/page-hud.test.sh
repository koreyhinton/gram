#!/bin/bash

# Prints the page and HUD tests as one Rust file (test.sh writes it to
# tests/page_hud.rs). draw-page.sh and draw-hud.sh run once with their
# drawing functions stubbed to record what they drew.
#
# The interface these tests fix:
#   draw-page.sh  binds Canvas. A PAGE_BG page at world (0, 0), PAGE_W x
#       PAGE_H, with a border 2 screen pixels thick.
#   draw-hud.sh   binds Canvas and Title. One line of text: the title, the
#       zoom in percent and the world point under the mouse.
#   banner.sh     binds Text. The text on a BANNER_BG box sized to it, across
#       the top of the canvas, right of the tree.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}page_Canvas=canvas
export ${v}hud_Canvas=canvas
export ${v}hud_Title=title
export ${v}banner_Text=message

cat << EOF
// Code generated by tests/page-hud.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the app's models cover more than these tests use
#![allow(dead_code)]

use macroquad::prelude::*;
use std::cell::RefCell;

EOF

# the app's constants and types
./models.sh

cat << EOF

#[derive(Debug, Clone, PartialEq)]
enum Drawn {
    Rect { rect: Rect, color: Color },
    RectLines { rect: Rect, thickness: f32, color: Color },
    Text { text: String },
}

thread_local! {
    static DRAWN: RefCell<Vec<Drawn>> = RefCell::new(Vec::new());
}

fn drawn() -> Vec<Drawn> {
    DRAWN.with(|list| list.borrow_mut().drain(..).collect())
}

fn draw_rectangle(x: f32, y: f32, w: f32, h: f32, color: Color) {
    DRAWN.with(|list| list.borrow_mut().push(Drawn::Rect { rect: Rect::new(x, y, w, h), color }));
}

fn draw_rectangle_lines(x: f32, y: f32, w: f32, h: f32, thickness: f32, color: Color) {
    DRAWN.with(|list| {
        list.borrow_mut().push(Drawn::RectLines { rect: Rect::new(x, y, w, h), thickness, color })
    });
}

fn draw_text(text: &str, _x: f32, _y: f32, _font_size: f32, _color: Color) {
    DRAWN.with(|list| list.borrow_mut().push(Drawn::Text { text: text.to_string() }));
}

// a stand-in width: 10 pixels a character
fn measure_text(text: &str, _font: Option<&Font>, _font_size: u16, _font_scale: f32) -> TextDimensions {
    TextDimensions { width: text.chars().count() as f32 * 10.0, height: 20.0, offset_y: 20.0 }
}

fn mouse_position() -> (f32, f32) {
    (200.0, 100.0)
}

fn screen_height() -> f32 {
    900.0
}

#[test]
fn the_page_is_a_white_sheet_at_the_origin() {
    let canvas = Canvas { offset: Vec2::ZERO, zoom: 2.0, panning: false, last_mouse: Vec2::ZERO };

    ` ./draw-page.sh ${v}page_ `

    assert_eq!(
        drawn(),
        vec![
            Drawn::Rect { rect: Rect::new(0.0, 0.0, PAGE_W, PAGE_H), color: PAGE_BG },
            // 2 screen pixels at 200%
            Drawn::RectLines { rect: Rect::new(0.0, 0.0, PAGE_W, PAGE_H), thickness: 1.0, color: PAGE_BORDER },
        ]
    );
}

#[test]
fn the_hud_shows_the_file_the_zoom_and_the_world_point() {
    let canvas = Canvas { offset: vec2(-50.0, 10.0), zoom: 2.5, panning: false, last_mouse: Vec2::ZERO };
    let title = "act.svg";

    ` ./draw-hud.sh ${v}hud_ `

    // the mouse at (200, 100) is world (-50 + 80, 10 + 40)
    match &drawn()[..] {
        [Drawn::Text { text }] => {
            assert!(text.starts_with("act.svg  |  250%  |  (30, 50)"), "{}", text);
        }
        other => panic!("{:?}", other),
    }
}

#[test]
fn the_banner_says_its_text_on_a_box_sized_to_it() {
    let message = "editing the <rect> in your editor";

    ` ./banner.sh ${v}banner_ `

    assert_eq!(
        drawn(),
        vec![
            Drawn::Rect { rect: Rect::new(TREE_W + 12.0, 10.0, 33.0 * 10.0 + 24.0, 34.0), color: BANNER_BG },
            Drawn::Text { text: message.to_string() },
        ]
    );
}
EOF
