#[derive(Debug, Clone, PartialEq)]
enum Drawn {
    Rect { rect: Rect, color: Color },
    RectLines { rect: Rect, thickness: f32, color: Color },
    Text { text: String },
}

thread_local! {
    static DRAWN: RefCell<Vec<Drawn>> = RefCell::new(Vec::new());
}

fn drawn() -> Vec<Drawn> {
    DRAWN.with(|list| list.borrow_mut().drain(..).collect())
}

fn draw_rectangle(x: f32, y: f32, w: f32, h: f32, color: Color) {
    DRAWN.with(|list| list.borrow_mut().push(Drawn::Rect { rect: Rect::new(x, y, w, h), color }));
}

fn draw_rectangle_lines(x: f32, y: f32, w: f32, h: f32, thickness: f32, color: Color) {
    DRAWN.with(|list| {
        list.borrow_mut().push(Drawn::RectLines { rect: Rect::new(x, y, w, h), thickness, color })
    });
}

fn draw_text(text: &str, _x: f32, _y: f32, _font_size: f32, _color: Color) {
    DRAWN.with(|list| list.borrow_mut().push(Drawn::Text { text: text.to_string() }));
}

// a stand-in width: 10 pixels a character
fn measure_text(text: &str, _font: Option<&Font>, _font_size: u16, _font_scale: f32) -> TextDimensions {
    TextDimensions { width: text.chars().count() as f32 * 10.0, height: 20.0, offset_y: 20.0 }
}

fn mouse_position() -> (f32, f32) {
    (200.0, 100.0)
}

fn screen_height() -> f32 {
    900.0
}

fn screen_width() -> f32 {
    1280.0
}

