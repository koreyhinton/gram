    }

    let mode = 4u8;
    let since = MODE_NOTICE_SECS - 0.01;
    ` ./mode-notice.sh ${v}notice_ `
    assert!(drawn().contains(&Drawn::Text { text: "4 => Rounded Rect Mode".to_string() }));

    let since = MODE_NOTICE_SECS;
    ` ./mode-notice.sh ${v}notice_ `
