#[test]
fn a_mode_change_says_so_for_a_few_seconds() {
    let mode = 0u8;
    let since = 0.5f64;
    ` ./mode-notice.sh ${v}notice_ `
    let list = drawn();
    assert!(list.contains(&Drawn::Text { text: "0 => Select Mode".to_string() }), "{:?}", list);
    // at the top right
    match &list[0] {
        Drawn::Rect { rect, color } => {
            assert_eq!(*color, NOTICE_BG);
            assert_eq!(rect.x + rect.w, 1280.0);
            assert_eq!(rect.y, 0.0);
        }
        other => panic!("{:?}", other),
    }

    // the old notifyTextArr (devbox@ed1a227)
    let mode = 1u8;
    ` ./mode-notice.sh ${v}notice_ `
    assert!(drawn().contains(&Drawn::Text { text: "1 => Line Mode".to_string() }), "{:?}", drawn());
    // devbox@8faf51d
    let mode = 2u8;
    ` ./mode-notice.sh ${v}notice_ `
    assert!(drawn().contains(&Drawn::Text { text: "2 => Arrow Mode".to_string() }), "{:?}", drawn());
    let mode = 3u8;
    ` ./mode-notice.sh ${v}notice_ `
    assert!(drawn().contains(&Drawn::Text { text: "3 => Rect Mode".to_string() }), "{:?}", drawn());
    // devbox@01c476e
    for (mode, name) in [
        (5u8, "5 => Decision Node Mode"),
        (6, "6 => Initial Node Mode"),
        (7, "7 => Final Node Mode"),
        (8, "8 => Fork/Join Node Mode"),
        (9, "9 => Text Mode"),
    ] {
        ` ./mode-notice.sh ${v}notice_ `
